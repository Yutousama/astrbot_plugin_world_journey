/**
 * 动作该怎么写 —— **只讲用法，不提供词表**。
 *
 * ## 这里为什么不再读宿主目录（2026-11-14 撤掉）
 *
 * 2026-11-01 踩过一次：她在气泡里写「【开心, 拍拍】」，宿主回一行「当前形象的词表里没有
 * 这些标记，已略过」—— 只有表情变了，人没动，而且**不报错**。当时的解法是现读宿主安装目录里
 * 的 `figure.json`（先读 `config.json` 找出用的是哪套立绘，再拼路径）。
 *
 * 这个解法**越了界**：按路径去读宿主安装目录，和直接改宿主的文件是同一类事 ——
 * 都是在拿"我恰好知道宿主的目录结构"当契约用。宿主改一次目录布局，这段就静默失效，
 * 而用户看到的是「她不动了」。市集作者 2026-11-14 明确要求撤掉（cortico-extensions#659）。
 *
 * ## 撤掉不丢信息
 *
 * **宿主已经把当前形象的词表放进了它自己的环境提示词**（桌宠 World 的 `{{pet.vocab}}`，
 * 见 Coopanion 仓 `packages/cortico-world-desktop-pet/src/ENV_PROMPT.md`）。
 * 模型本来就看得到，我们没必要、也不该自己再抄一份 —— 两份一旦不一致，
 * 错的那份还长得像是对的。
 *
 * 所以这个文件只剩一件事：**什么场合该动一下、写在哪儿、为什么别写英文 id**。
 */

/**
 * 场合 → 该做什么动作。
 *
 * 这一层是**语义**不是词表：说的是「这种时候该动一下」，具体写哪个名字由她那边的
 * 词表决定。所以这里用「走或跑」这种类别说法 —— 词表里叫什么，她照着挑就是了。
 *
 * 老版本会拿这张表跟读到的词表**求交**，没有的整条丢掉。现在不读了，
 * 但不能因此变成承诺：措辞上留了「没有就换一个意思接近的」，避免她硬写一个不存在的词。
 */
const BY_OCCASION: readonly { readonly when: string; readonly want: string }[] = [
  { when: '赶路、走得急', want: '走或跑' },
  { when: '累了、心里难受', want: '坐下' },
  { when: '看远处的风景', want: '张望' },
  { when: '被什么震住', want: '怔住（没有就换一个停顿感的）' },
  { when: '刚到、兴奋', want: '小跳' },
  { when: '冷', want: '发抖' },
  { when: '高反、晕车', want: '晕' },
  { when: '遇上麻烦', want: '退半步、发抖' },
  { when: '吃到好吃的', want: '扑腾' },
  { when: '安静待着', want: '坐下、闭眼听' },
  { when: '客气一下', want: '点头、招手' },
];

/**
 * 拼成提示词里那段文字。
 *
 * 三件事按重要性排：先写对格式（写错等于白写），再给场合，最后留一条「没有也能写」的出口 ——
 * 那条不是客套：她写不出词的时候会开始瞎编名字，而瞎编的代价是**静默丢掉**，
 * 她永远学不会。给个「会被记下来」的说法，至少让她愿意试。
 */
export function actionsPrompt(): string {
  const lines = BY_OCCASION.map((o) => `${o.when} ${o.want}`);
  return [
    '动作写在方括号里，跟表情并列：`【平静, 坐下】`。只写表情等于没动。',
    '**名字只用你手上那份词表里真有的**（见「当前形象的词表」）。写表外的会被静默丢掉 —— 人站着不动，还不报错。用中文名，别写英文 id。',
    `场合对动作：${lines.join('；')}。`,
    '**词表里没有的动作也可以写。** 会被忽略，但会被记下来 —— 攒到一定次数，就有人把它做出来。',
  ].join('\n');
}
