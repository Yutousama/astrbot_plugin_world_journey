function detailPrompt(scene: PhotoScene): string {
  /* 用城市 + 日期定一个稳定的序号：同一天不会一会儿这样一会儿那样。 */
  const seed = [...`${scene.city}${scene.month ?? 1}${scene.day ?? 1}`]
    .reduce((n, ch) => (n ^ ch.charCodeAt(0)) * 16777619 >>> 0, 2166136261) >>> 0;
  const city = scene.cityId ? cityById(scene.cityId) : null;
  const region = city ? regionOf(city) : null;
  const pool = !city ? DETAILS_ANY
    : city.country === 'CN' ? DETAILS_CN
    : region === 'tropical' || region === 'eastAsia' || region === 'eastAsiaCold'
      || region === 'mediterranean' || region === 'desert' ? DETAILS_WARM
    : region ? DETAILS_EU
    : DETAILS_ANY;
  /*
   * **取高位，不取低位。** 这个哈希的低几位几乎只由城市名最后几个字决定，
   * 而「同一天」的城市集合里那几位是相同的 —— 实测八座俄国/波兰城全落到同一条。
   * 右移 11 位之后才真正打散。
   */
  const item = pool[(seed >>> 11) % pool.length]!;
  const dsun = sceneSun(scene);
  const light = lightLine({
    phase: dsun.phase, overcast: dsun.overcast, precip: dsun.precip, indoor: true,
    whiteNight: dsun.whiteNight,
  });
  return `一张特写照片：${item}。${light}。`
    + `45 度俯拍，主体偏在一侧、不摆正中，浅景深，焦点落在最亮的那一小块上。${NO_PEOPLE}。${NO_TEXT}。`;
}

/* ============================================================================
 * 光：用太阳高度角，不用钟点
 * ============================================================================
 *
 * ## 为什么把整层判据换掉（2026-11-12）
 *
 * 原来所有模板都按**整数小时**分档：`hour < 9` 清晨、`< 15` 正午、`< 20` 黄昏、
 * 之后入夜。这套在兰州勉强能用，一离开兰州就处处是错：
 *
 * | 现场 | 旧判据说 | 实际 |
 * |---|---|---|
 * | 成都 11 月 19 点 | 黄昏的金色光线 | 日落 18:05，已经黑透 |
 * | 成都 11 月 19 点 | `daylitAt` 判「有日光」→ 尾句「自然光」 | 同上，一句话里既黑又亮 |
 * | 喀什 11 月 20 点 | 入夜，只有零星窗灯 | 太阳刚落下，天边还亮着 |
 * | 漠河 6 月 23 点 | 深夜，天是黑的 | 整夜不黑 |
 * | 悉尼 12 月 19 点 | 黄昏 | 南半球夏天，太阳高得很 |
 *
 * 这五条**没有一个能靠调整小时数修好** —— 因为钟点里根本不含有「太阳在哪儿」这个量。
 * 同一个 19 点，在成都、喀什、漠河、悉尼是四种完全不同的光。
 *
 * 所以改成算**太阳高度角**：纬度 + 赤纬 + 时角，一个公式管住全部情况，
 * 极昼极夜、南北半球反转、高纬夏天不黑，全是它的自然结果，不用再列特例。
 *
 * 顺手把**经度**也算进去。中国全境用一个时区，喀什（东经 76°）的钟点比太阳时
 * 快将近三小时 —— 不算经度，西部城市的每一张照片都会偏亮两三个小时。
 *
 * ## 一句话一件事
 *
 * 这一层只回答「地面被什么照着」。**天上的颜色由 `skyLine` 说，
 * 季节的可见物由季节句说。** 三者互不越界，才不会出现
 * 「黄昏的金色光线」和「灰白低云、没有太阳」同时出现在一段里 ——
 * 那种矛盾不是措辞问题，是同一件事被三个地方各说了一遍。
 */

/** 一年中的第几天（用每月 15 号做代表日，误差不超过一周，对光的分档无影响）。 */
function dayOfYear(month: number): number {
  return 30.4 * ((((Math.trunc(month) - 1) % 12) + 12) % 12) + 15;
}

/**
 * 真太阳时。
 *
 * 两个修正：经度（东经越靠西，太阳越晚到头顶）和时区（含夏令时）。
 * 均时差（±16 分钟）忽略 —— 它影响的是「日出早两分钟还是晚两分钟」，
 * 换不到任何一个光档。
 */
function solarHourOf(hour: number, lon: number, tz: string, month: number): number {
  const off = tzOffsetHours(tz, new Date(Date.UTC(2026, Math.max(0, month - 1), 15, 12)));
  if (!Number.isFinite(off)) return hour;
  const standardMeridian = off * 15;
  return hour + (lon - standardMeridian) / 15;
}

/**
 * 这一刻太阳在地平线以上多少度。负数 = 已经落下去多少度。
 *
 * `lon` / `tz` 不给就退回「当地钟点 = 太阳时」（老调用方不用改，
 * 代价是西部城市会亮得偏早）。
 */
export function sunAltitude(
  lat: number,
  month: number,
  hour: number,
  lon?: number,
  tz?: string,
): number {
  if (!Number.isFinite(lat)) return 0;
  const sh = lon !== undefined && tz ? solarHourOf(hour, lon, tz, month) : hour;
  const decl = 23.44 * Math.sin((2 * Math.PI / 365) * (dayOfYear(month) - 81));
  const H = 15 * (sh - 12);
  const rad = Math.PI / 180;
  const sinAlt = Math.sin(lat * rad) * Math.sin(decl * rad)
    + Math.cos(lat * rad) * Math.cos(decl * rad) * Math.cos(H * rad);
  return (Math.asin(Math.max(-1, Math.min(1, sinAlt))) / rad);
}

/**
 * 光的档位。**按角度分，档界贴着能看见的现象划。**
 *
 * 几点几分只是这些角度在人间的投影，换个纬度就投影歪了 ——
 * 所以要判的是角度，不是钟点。
 */
export type SunPhase =
  | 'noon'      // 太阳高悬，影子缩在脚下
  | 'day'       // 正经白天
  | 'slant'     // 斜光，立面有明暗
  | 'low'       // 低角度暖光，影子拉长
  | 'golden'    // 太阳贴着地平线，金红
  | 'afterglow' // 已落下，天边余晖
  | 'blue'      // 蓝调
  | 'twilight'  // 只剩天边一线
  | 'night';    // 全黑

export function sunPhase(alt: number): SunPhase {
  if (alt >= 50) return 'noon';
  /* 30° 以上影子还短；15–30° 才是「斜光」——兰州六月十八点太阳在 26°，
     那时候的影子已经斜了，不该算正白天的平光。 */
  if (alt >= 30) return 'day';
  if (alt >= 15) return 'slant';
  if (alt >= 2) return 'low';
  if (alt >= -1) return 'golden';
  if (alt >= -6) return 'afterglow';
  if (alt >= -10) return 'blue';
  if (alt >= -16) return 'twilight';
  return 'night';
}

/** 这个档位算不算「天上有日光」——供机位、噪点、负向共用。 */
export function phaseIsDaylit(p: SunPhase): boolean {
  return p === 'noon' || p === 'day' || p === 'slant' || p === 'low' || p === 'golden';
}

/**
 * 地面的光。**这是整条提示词里唯一被允许描述光源的地方。**
 *
 * 参数只有四个，因为能画出来的差别只有四种：太阳多高、有没有云挡、在下什么、在室内还是室外。
 * 别的（季节、地点、情绪）都不该影响光 —— 一让它们进来，就会出现
 * 「成都的冬天没有太阳」这种把气候断言混进光照句的写法。
 */
export interface LightInput {
  readonly phase: SunPhase;
  /** 云把太阳挡住了。白天要说「压平」，不能说「金色」。 */
  readonly overcast: boolean;
  /** 雨、雪、雾 —— 只在灯下/光里看得见的那种。 */
  readonly precip: string;
  /** 室内（食物、小物）：窗光或一盏灯，没有「天空」这回事。 */
  readonly indoor: boolean;
  /** 白夜：这一夜天根本不会黑透（午夜太阳高度还在 -16° 以上）。
   *
   * 不单列这个开关的话，圣彼得堡六月的 23 点会被算成「几乎全黑」——
   * 而那一刻窗外还看得清房子。**白夜不是夜。**
   */
  readonly whiteNight?: boolean;
  /**
   * 这一张在**城里**（2026-11-15）。
   *
   * 起因：Mr.Q 发来一张兰州夜景 —— 满天星、几处窗灯、对岸黄土坡、低矮平房，
   * 是黄土高原的村子，而他家在城关区。查下来提示词是
   * 「只有几处窗灯和路灯，照不亮周围」—— `night` 档一直只有这一句，
   * 那是**郊野**的语言。城里夜里路灯连成线、桥上有灯、楼里的窗还亮着，
   * 一句「几处」就把整座城抹成了村。
   *
   * 判据同 §17：**按「这是什么地方」给，不按「长什么样」猜。**
   * 拍整座城（无 `spot`）、在家、景点判为 `urban` → 城里。
   */
  readonly urban?: boolean;
}

/**
 * 地面的光。**这是整条提示词里唯一被允许描述「照明」的地方。**
 *
 * 只讲地面：影子多长、物体边缘亮不亮、还有没有别的光源。
 * **一个字都不提天的颜色** —— 那是 `skyLine` 的活。
 * 两边都写天空，就会出现「黄昏的金色光线」和「灰白低云」同时成立的段子。
 */
export function lightLine(input: LightInput): string {
  const { phase, overcast, indoor, whiteNight, urban } = input;

  if (whiteNight) {
    return indoor
      ? '屋里亮着灯，窗玻璃上还映着外面的光'
      : '光是灰白的，像傍晚一样，什么都还认得出来';
  }

  if (indoor) {
    if (phase === 'noon' || phase === 'day') return '光从窗子斜进来，桌上有一块亮';
    if (phase === 'slant' || phase === 'low') return '窗光斜进来，桌面上一块暖色';
    if (phase === 'golden' || phase === 'afterglow') return '屋里已经偏暗，只有靠窗那一块还亮着';
    return '一盏暖黄的灯从上方罩下来，桌面反光';
  }

  /* 云挡着太阳：白天这几档一律不许出现「金色」「阳光」这类词。 */
  if (overcast) {
    if (phase === 'noon' || phase === 'day') return '光被压平了，地上没有影子';
    if (phase === 'slant' || phase === 'low') return '云压着光，光很散，看不出太阳在哪';
    if (phase === 'golden') return '太阳在云后面，光很平，物体边缘不发亮';
  }

  switch (phase) {
    case 'noon': return '顶光，影子几乎落在脚下';
    case 'day': return '日光偏亮，影子短而清楚';
    case 'slant': return '光斜着打过来，立面上分出明暗';
    case 'low': return '光从很低的角度打过来，影子拖得很长';
    /* 颜色只在天那一句说（`skyLine`）。这儿再说一遍橙红，等于给晚霞加倍。 */
    case 'golden': return '太阳贴着地平线，物体边缘发亮';
    case 'afterglow': return '太阳刚落，地面已经暗下来，影子没有了';
    case 'blue': return '物体只剩下轮廓，窗灯刚亮';
    case 'twilight': return '几乎全黑，只看得清近处物体的轮廓';
    /*
     * 夜里这一档要分城里和野外（2026-11-15）。
     *
     * 原来只有野外那一句 —— 城里也照它画，「几处窗灯」就把整座城抹成了村。
     *
     * **只写每座城、每个景点都有的东西。** 第一版写的是「桥上的灯、楼里的窗」——
     * 兰州有桥、喀什老城的窄巷没有；城市有楼、兵马俑坑边没有。
     * 写成这样，模型会替喀什造一座桥、给坑道配一排居民楼。
     * 路灯是唯一处处成立的：路面被打亮、往远处连成线，这一条就够把「城」立住。
     *
     * **没做「野外再分荒野」那一档**：试过用 `spotProfile().setting === 'wild'`
     * 判无人区（戈壁、雪山没有窗灯），被 `photo-subject` 打了回来 ——
     * 「婺源的江岭」判成 mountain/wild，可那是有人住的梯田村。
     * `wild` 只说明「不在市区」，说明不了「有没有人住」。判不出就别猜，走老路。
     */
    default: return urban
      ? '路灯一盏接一盏，把地面照出一片一片的亮，远处连成一条'
      : '没有别处的光，只有几处窗灯和路灯，照不亮周围';
  }
}

/**
 * 天空。**只在画面里真有天的时候调用。**
 *
 * 和 `lightLine` 的分工是硬线：那边管「地面被什么照着」，这边管「抬头看见什么颜色」。
 */
export function skyLine(
  phase: SunPhase, overcast: boolean, precip = '', whiteNight = false, urban = false,
): string {
  if (whiteNight) {
    return overcast || /雨|雪/.test(precip)
      ? '天没有黑透，是压着云的一片灰白'
      : '天没有黑透，北边一直留着灰蓝';
  }
  /* 夜里看不见云是什么颜色 —— 阴和晴在半夜长得一模一样。 */
  if (phase === 'night' || phase === 'twilight') {
    if (phase !== 'night') return '天边只剩一线灰蓝，上面已经黑';
    /*
     * 城里看不见这么密的星（2026-11-15）。光污染把暗星全吃掉，
     * 只剩最亮的一两颗，天本身也不是纯黑，是被灯映成深灰。
     * 一句「星星看得清」在市区是假的，而且它会把这幅画推向野外。
     */
    return urban
      ? '天是深灰的，被底下的灯映亮，只看得见一两颗星'
      : '头顶是黑的，星星看得清';
  }
  /*
   * 蓝调也要看天。阴天的蓝调时刻不是「饱和的深蓝」——
   * 太阳早就被云挡了，天上是一整片正在发暗的灰。
   * 这一支原来排在阴天判断之前，于是阴雨天的傍晚总被画成通透的蓝。
   */
  if (phase === 'blue') {
    return overcast || /雨|雪|雾/.test(precip)
      ? '天是发暗的灰蓝，看不出云，也没有星'
      : '蓝调时刻，天空是饱和的深蓝，快满到顶';
  }
  if (overcast || /雨|雪|雾/.test(precip)) {
    return phase === 'afterglow' || phase === 'golden'
      ? '天是一整片压低的灰云，只有地平线那儿透出一点亮'
      : '天是一整片灰白的云，低低压着';
  }
  switch (phase) {
    case 'noon': return '天是饱和的蓝，顶上一两朵积云';
    case 'day': return '天是浅蓝的，云很少';
    case 'slant': return '天往浅里退，西边有一层薄云';
    case 'low': return '天还是蓝的，只有贴近地平线那一带泛暖';
    case 'golden': return '天从橙红过渡到深蓝';
    default: return '地平线一层橙，往上迅速转深蓝';
  }
}

/**
 * 天气的**可见后果**。
 *
 * 不写「天气阴」——「阴」是气象台的分类，画不出形状。写它还会让模型给场景
 * 铺一层灰蓝天光，这正是「半夜拍得像小雨天的白天」的来源。
 * 能画出来的只有：雨丝、湿地面、积雪、雾把远处吃掉。
 */
export function weatherLine(precip: string, phase: SunPhase): string {
  const t = String(precip ?? '');
  if (!t) return '';
  const dark = !phaseIsDaylit(phase);
  if (/雨/.test(t)) {
    return dark ? '雨在灯光里看得见，地面湿亮' : '雨丝在光里看得见，地面湿得反光';
  }
  if (/雪/.test(t)) {
    return dark ? '雪落在灯光里，地上已经积了一层' : '雪片在光里看得见，地上积了一层';
  }
  if (/雾|霾/.test(t)) return dark ? '雾把远处吃掉，只剩近处几盏灯' : '雾把远处吃掉一半';
  if (/沙|尘/.test(t)) return '浮尘浮在光里';
  return '';
}

/**
 * 这一刻有没有日光。
 *
 * 2026-11-10 从 `photoPrompt` 里抽出来 —— 因为**不只是提示词要判断这件事**：
 * 夜里还要追加负向词、还要把 cfg 提上去（cfg 2.5 时模型不太听得进
 * 「天上没有星」，实测三张都画了星星）。三处必须用同一个判据，
 * 各自写一份迟早分叉。
 *
 * 2026-11-12 换掉实现：原来靠 `lightBand` + 「6 点到 20 点算白天」，
 * 于是成都 11 月的 19 点被判成白天，尾句照样给「自然光」——
 * 「晚上拍得跟白天一样」这条报障一直没断根，就是这里。
 *
 * `lon` / `tz` 可选：`world.ts` 那条路径只拿得到纬度，不传就退回钟点近似。
 */
export function daylitAt(lat: number, month: number, hour: number, lon?: number, tz?: string): boolean {
  return phaseIsDaylit(sunPhase(sunAltitude(lat, month, hour, lon, tz)));
}

/**
 * 这一张要不要按「夜拍」处理（追加负向 + 提 cfg）。
 *
 * 正常拍照：看此刻当地有没有日光。
 *
 * **重拍（`repaint`）一律不算夜拍**（2026-11-11）。理由不是宽容，是数据对不上：
 * 重拍一张几天前的照片时，`dateKey` 用的是那张的日期，`hour` 却来自「此刻几点」——
 * 白天拍的，深夜点重拍就被判成夜拍，负向里被塞进「天上没有星／地平线不要发白」，
 * cfg 从 2.5 提到 3.3。而用户在同一操作里写的提示词明摆着是白天（「雨后的湖边小路」），
 * 两下互斥，画面要么被打暗、要么跟提示词打架。
 *
 * 抽成纯函数是为了能测：这个判断埋在 `maybePhoto` 里，隔着十几层拿不到，
 * 改错了没人发现 —— 白天点重拍看着正常，深夜才炸。
 */
export function shotIsNight(opts: {
  /** 重拍某一具体的那张（用他自己写的整段提示词）。 */
  repaint: boolean;
  lat: number;
  month: number;
  hour: number;
  lon?: number;
  tz?: string;
}): boolean {
  if (opts.repaint) return false;
  if (daylitAt(opts.lat, opts.month, opts.hour, opts.lon, opts.tz)) return false;
  /*
   * **白夜不算夜拍**（2026-11-12 实图之后）。
   *
   * 漠河夏至 22 点：提示词写着「天没有黑透，像傍晚一样，什么都还认得出来」，
   * 配的却是夜拍的负向（`sky glow`、`bright horizon`）和 cfg 3.3 ——
   * 出来是一张深夜，天上连一丝灰蓝都没有。**负向在跟正向对着干。**
   *
   * 判据：午夜太阳高度还在 -16° 以上，这一夜就没有黑透过，按白天那套参数走。
   */
  const altMid = sunAltitude(opts.lat, opts.month, 0, opts.lon, opts.tz);
  return !(altMid > -16);
}

/**
 * 夜拍要**追加**到负向的那些词。
 *
 * 光靠正向说「天上没有月亮，也没有星」压不住 —— cfg 2.5 时模型照画。
 * 实测：加负向能压掉地平线那道鱼肚白，星星还要再配一次 `cfg` 提高才干净。
 *
 * 只放**夜里一定不该有**的东西：星星、月亮、天光、日出、被照亮的地面。
 * 白天用的负向一概不掺进来。
 */
export function nightNegative(weather = ''): string {
  /*
   * **星星不是「夜里一律不要」。**（2026-11-10 当天被 Mr.Q 纠回来）
   *
   * 上一版把 `stars, moon, moonlight` 写死在负向里，本意是修「阴天的夜空
   * 冒出三颗星」—— 但那样一来，她**抬头看天的时候也拍不出星星**了，
   * 而看星星正是夜里最该拍的事之一。
   *
   * 判据：**看天气，不看钟点。** 阴雨天确实不该有星；晴夜当然该有，
   * 哪怕她只是在路上顺手拍一张，天上带几颗星也是真的。
   *
   * 抬头拍天那条另有 `skyOf` 负责说「今晚天上有几颗」—— 它按纬度和云量
   * 算过，比这里一刀切准。
   */
  const cloudy = /阴|雨|雪|雾|霾|沙|尘/.test(String(weather));
  return [
    ...(cloudy ? ['stars', 'moon', 'moonlight'] : []),
    /*
     * 抬头那张实测还留着一圈发白的地平线 —— 那是「夜空照片」里最常见的
     * 光污染带。正向写「地平线不发白」压不住，得进负向点名。
     */
    'sky glow', 'bright horizon', 'light pollution', 'glowing horizon', 'gradient sky',
    'blue hour', 'dawn', 'sunrise', 'daylight',
    'sunlit field', 'floodlit', 'overexposed', 'glowing ground', 'green field', 'bright grass',
  ].join(', ');
}

export type LightBand = 'polarNight' | 'polarDay' | 'whiteNight' | 'darkEarly' | 'brightLate' | '';

/**
 * **高纬特例档位（老接口）。**
 *
 * 2026-11-12 起提示词内部不再用它 —— 判光改成了 `sunAltitude`，
 * 那一套把极昼、极夜、白夜、南北半球全算成同一个公式的结果，不需要档位表。
 *
 * 留着它是因为：它是导出的接口（外部脚本、测试在用），而且「这地方此刻是不是特例」
 * 这个问题本身仍然有意义。**新代码不要用它判光**，用 `sunPhase(sunAltitude(...))`。
 */
export function lightBand(lat: number, month: number, hour: number): LightBand {
  if (!lat) return '';
  const absLat = Math.abs(lat);
  /* 南半球的一月等于北半球的七月 —— 先翻成「当地的季节月份」。 */
  const m = lat >= 0 ? month : ((month + 5) % 12) + 1;
  const winter = m === 12 || m === 1 || m === 2;
  const summer = m === 6 || m === 7 || m === 8;
  if (absLat >= 66) {
    if (winter) return 'polarNight';
    if (summer) return 'polarDay';
  }
  /* 白夜：北纬 58° 以上（列宁格勒、彼得罗扎沃茨克），夏至前后天不黑透。 */
  if (absLat >= 58 && summer) return 'whiteNight';
  if (absLat >= 45 && winter && hour >= 17) return 'darkEarly';
  if (absLat >= 45 && summer && hour >= 20) return 'brightLate';
  return '';
}

/**
 * 一天里的哪一段。极简模式只用这个词说时间 —— 「下午」两个字模型就懂，
 * 「斜光把影子拉得很长，色温偏暖」这种它反而不如自己会。
 */
function dayPart(hour: number): string {
  if (hour < 5) return '深夜';
  if (hour < 8) return '清晨';
  if (hour < 11) return '上午';
  if (hour < 14) return '正午前后';
  if (hour < 17) return '下午';
  if (hour < 19) return '傍晚';
  if (hour < 22) return '晚上';
  return '深夜';
}

/**
 * ## 极简模式：只写「城市 + 景点 + 光」（2026-11-11）
 *
 * 用户沃兔拿豆包做了我这台机器做不到的对照实验：
 *
 *   「我在豆包**只写地名和景点、不加其它提示词**的话，出现的就是正常的景点照片，
 *     建筑也能对上。」
 *
 * 这句话推翻了我这几天的工作方向。我一直在「给它补描述」——城市锚点、景点锚点、
 * 季节句、体感、机位，一层层加；他实测出来**不补反而对**。
 *
 * 本机同 workflow 同种子也能复现这个方向：281 字的模板画成江南水乡，
 * 60 字的画对川西，30 字（「成都文殊院，川西佛教寺庙，红墙木构大殿」）也对。
 *
 * **所以不是「描述写得不够好」，是模型本来就认识这些地方。** 补得越多，
 * 那些地名就越容易被我写的形容词盖过去 —— 而我的形容词是按「一座城的平均长相」
 * 写的，套到具体景点上就成了一块砖。
 *
 * ### 保留了什么，为什么
 *
 * - **时段**：不写它会把夜里画成白天。这是唯一一个「不写就一定错」的事实。
 * - **天气**：下雨下雪是眼前的真事，模型猜不到。
 * - **她写的画面 / 用户写的怎么拍**：那是人的意图，优先级本来就最高（1.2.8 的顺序）。
 * - **一条极短的硬约束**：不写「没有人物」，模型很爱往空镜里塞一个陌生人。
 *
 * ### 什么时候不启用
 *
 * 抬头拍天（`view: 'sky'`）和在路上（`onRoad`）退回完整模板 ——
 * 前者要按纬度、月份、天气算天上到底是星是云，这个不写就是编；
 * 后者画面不属于某一座城，地名那套在这儿不成立。
 */
function minimalPrompt(scene: PhotoScene): string {
  const raw = (scene.style ?? '').trim();
  const bare = raw.toLowerCase() === 'none';
  const custom = raw !== '' && !bare;
  const cast = (scene.cast ?? '').trim();
  const lead = bare ? '' : custom ? `${raw}：` : '一张真实旅行照片：';

  const place = scene.spot
    ? (scene.spot.startsWith(scene.city) ? scene.spot : `${scene.city}${scene.spot}`)
    : scene.city;

  const weather = (scene.weather ?? '').trim();
  /*
   * 极简版只留一个词说时间，但那个词**必须和太阳对得上**：
   * 19 点的成都是夜里，不是「傍晚」。所以先用太阳判有没有日光，
   * 再退回 `dayPart` 的粗分。
   */
  const msun = sceneSun(scene);
  const part = msun.whiteNight ? '天没黑透' : !msun.daylit ? '深夜' : dayPart(scene.hour);
  const light = [weather, part].filter(Boolean).join('，');

  /*
   * **景点锚点在这条路上要留着（2026-11-11 本机四张对照之后）。**
   *
   * 极简版最初连景点锚点一起砍掉，结果两极分化：
   *
   * | 地方 | 完整 131 字 | 纯极简 28 字 |
   * |---|---|---|
   * | 成都文殊院 | 木构青瓦的**街**（被「街巷两侧」带偏） | 大殿重檐 + 石阶 + 古树 = **寺院，对了** |
   * | 泉州清净寺 | 花岗岩院墙 + **尖拱门洞** + 空阔石板地 | 燕尾脊 + 红砖 + 木构 = **中式庙宇，全错** |
   *
   * 差别在**模型认不认识这个地方**。文殊院它认识，一句地名就够，我补的
   * 「街巷两侧是老房」反而把寺院说成了街。清净寺它不认识，只从「寺」字
   * 认出个庙 —— 这时候锚点是唯一的信息来源，砍掉就只剩模型的瞎猜。
   *
   * 所以：**城市锚点砍（那是「一座城的平均长相」，最容易带偏），
   * 景点锚点留（那是「这个地方到底什么样」的唯一事实）。**
   * 没写景点锚点的（西街这类和城市同调的）就真的只发地名。
   */
  const own = spotLook(scene.cityId, scene.spot);

  const describe = (scene.describe ?? '').trim().replace(/。+$/, '');
  const focus = (scene.focus ?? '').trim().replace(/。+$/, '');

  const parts = [
    lead,
    describe ? `${describe}。` : '',
    focus ? `这一张想这么拍：${focus}。` : '',
    own ? `${place}，${own}，${light}。` : `${place}，${light}。`,
    cast ? `画面里有一个人：${cast}。不要出现可读的文字。` : '没有人物，没有文字。',
  ];
  return parts.filter(Boolean).join('');
}

/**
 * 这一张的天文条件，算一次给所有模板用。
 *
 * 五个字段就是「光」这一层全部能知道的事：
 * 太阳多高、档位、算不算白天、有没有云挡、在不在下雨雪、是不是白夜。
 * 模板拿到的只有这些，拿不到「成都的冬天没有太阳」这种东西 ——
 * 那是气候断言，一旦混进光照句，换个季节就自相矛盾。
 */
export interface SceneSun {
  readonly alt: number;
  readonly phase: SunPhase;
  readonly daylit: boolean;
  readonly overcast: boolean;
  readonly precip: string;
  readonly whiteNight: boolean;
}

export function sceneSun(scene: PhotoScene): SceneSun {
  const city = scene.cityId ? cityById(scene.cityId) : null;
  const lat = city?.lat ?? 0;
  const month = scene.month ?? 1;
  const alt = sunAltitude(lat, month, scene.hour, city?.lon, city?.tz);
  /*
   * 午夜那一刻的高度决定「这一夜会不会黑透」。
   * 高纬夏天（漠河、圣彼得堡、柏林）午夜在 -16° 以上，天根本不会黑 ——
   * 这不是特例，是同一个公式在另一个时刻的取值。
   */
  const altMid = sunAltitude(lat, month, 0, city?.lon, city?.tz);
  const phase = sunPhase(alt);
  const weather = String(scene.weather ?? '');
  /*
   * 没有天气数据时，**川渝和华中冬半年按「有云」处理**。
   *
   * 这不是风格偏好，是气候事实：成都年日照一千小时上下，是全国最少的一档，
   * 冬天连着十天不见太阳是常事。这一层原来写在 `avoidLine` 里
   * （「天色常是灰白的，看不见蓝天」），是一句否定句，还排在硬约束后面 ——
   * 现在改成这里的默认值，由 `skyLine` / `lightLine` 用正面的话说出去。
   *
   * 天气里明说了「晴」就按晴，**任何气候默认值都不该盖过真实天气**。
   */
  const region = city ? regionOf(city) : null;
  const basinWinter = (region === 'sichuan' || region === 'central' || region === 'jiangnan')
    && (month >= 11 || month <= 3);
  return {
    alt,
    phase,
    daylit: phaseIsDaylit(phase),
    /* 「阴」在气象上是分类，在这里只是「太阳被挡了」。 */
    overcast: weather !== '' ? !/晴/.test(weather) : basinWinter,
    precip: /雨|雪|雾|沙|尘/.test(weather) ? weather : '',
    whiteNight: altMid > -16 && alt <= -1,
  };
}

export function photoPrompt(scene: PhotoScene): string {
  /*
   * 极简模式在分流之前拦一道（2026-11-11）。见 `minimalPrompt` 的注释。
   * 抬头拍天和在路上不走这条 —— 那两个场景缺了事实就会变成编。
   */
  if (scene.minimal && !scene.onRoad && (scene.subject ?? scene.view) !== 'sky') {
    return minimalPrompt(scene);
  }
  /*
   * 先按题材分流（2026-11-06）。
   * 这是那个 bug 的正面修法：原来不管用户说什么，都走「城市 + 景点」那一条，
   * 于是「拍晚饭」出来还是那处风景。现在题材写在 scene 里，各走各的模板。
   *
   * `subject` 没传时，按老的 `view` 推 —— 老调用方一个字段都不用改。
   */
  const subject = scene.subject ?? (scene.view === 'sky' ? 'sky' : 'ground');

  /*
   * 纬度和「有没有日光」提到最前面 —— 因为**场景描述本身要看它**（2026-11-10）。
   *
   * 前几版只在「光」那一句上做文章，而 `where` 里那句
   * 「一带的田野、村庄和路」是白天的语言：它默认可视、有颜色、有细节。
   * 后面无论怎么补「天是黑的」「照不亮周围」，模型都会给田铺一层暖光 ——
   * 三张实测里田一直是亮的。
   *
   * 判据：**夜里的窗外认不出田野和村庄，只认得出几个亮点。**
   * 所以夜里连这句都不能这么说。
   */
  const nowCity = scene.cityId ? cityById(scene.cityId) : null;
  const latNow = nowCity?.lat ?? 0;
  /*
   * 太阳这一层只算一次，后面所有模板读同一组值（2026-11-12）。
   *
   * 原来这里只有一句 `daylitAt(lat, month, hour)`，而各模板自己还按小时再分一遍档；
   * 两套判据并存的结果是「光说天黑了、尾句说自然光」。现在没有第二套了。
   */
  const sun = sceneSun(scene);
  const night = !sun.daylit;
  /*
   * 抬头拍天：老调用方用 `view='sky'`，新调用方用 `subject='sky'` —— 两条都要认。
   * 提到这里是因为「季节、天空、极简」三处都要先问它一句。
   */
  const sky = scene.view === 'sky' || scene.subject === 'sky';

  /*
   * ## 时间 / 天气 / 可见性，各算一次（2026-11-10 全量体检）
   *
   * 体检出的七处「对不上」，根子都是**判断散在各处**：有的按小时、有的按天气、
   * 有的谁都不判（写死在数据里）。这里算一次，后面所有模板读同一组值。
   *
   * 2026-11-12：`weather` 那一组已经搬进 `sceneSun()` —— 太阳高度、有没有云、
   * 在下什么，现在是同一个函数一次算完，模板里不再各自判天气。
   */
  /* 特写里没有环境：食物和细节都不该提到天空。 */
  const closeup = subject === 'food' || subject === 'detail';

  /**
   * 剥掉季节句里「天是什么样」的那些分句。
   *
   * ## 为什么从「按情况剥」改成「一律剥」（2026-11-12）
   *
   * 原来是三条条件：夜里剥天空、晴天剥「没有太阳」、特写剥天空。
   * 这是拿正则给一句气候断言打补丁 —— 成都一月那句
   * 「天空是一整片灰白低云，没有太阳也没有影子（这一带冬天日照极少）」
   * 只在 `night` 或 `sunny` 时才被剥，傍晚照样漏进去，
   * 于是同一段里既有「黄昏的金色光线」又有「没有太阳」。
   *
   * 判据很简单：**天的颜色只有一个来源**（`skyLine`），
   * 别的句子一律不许说天。所以不再看情况，见到就剥。
   */
  const trimScene = stripSkyClauses;
  /*
   * **季节要跟到每个题材里**（2026-11-07）。
   *
   * 用户报的是「同一座城，街景对得上，换成吃的就变江南了」。查下来不是食物一条的问题：
   * 这几个模板都是提前 return 的，**只有 ground 那条拼了视觉锚点和季节**。
   * 食物自己给了桌子窗子（见 `foodPrompt`），街景和细节还缺这一句。
   *
   * 节日那条不加：它的文案本身就是按日期写的（正月挂灯笼、端午粽子），
   * 再叠一句「阔叶落尽」只会互相打架。
   */
  /*
   * 这个季节在这座城长什么样 —— **算一次，所有题材共用**。
   *
   * 2026-11-12：原来 `withSeason` 自己调一次 `seasonLine`，
   * `photoPrompt` 末尾又调一次，两处规则不同 —— 于是街景在黑夜里
   * 照样挂着「叶子被晒得发亮」（一致性测试当场抓住）。
   * 现在只有一个入口，规则只有一条：**没有日光就不写季节。**
   */
  /**
   * 这个点在不在室内 —— 三处要它：季节句、天空句、「周边一带」。
   *
   * 室内一条铁律：**凡是站在屋里看不见的东西，一个字都不写。**
   * 实测（2026-11-14）：敦煌博物馆只剩「室内，展柜和展墙」+ 周边街景时，
   * 出图仍是一条村街 —— 矛盾的两半里，写得多的那半赢。
   */
  const spotIndoor = Boolean(scene.spot)
    && !scene.onRoad && !sky
    /* 只认 `ground`：拍街景、拍特写、拍吃的时候，室内与否跟她站在哪儿无关。 */
    && (scene.subject ?? 'ground') === 'ground'
    /*
     * **有专属锚点时以锚点为准。** 西安碑林博物馆名字里带「博物馆」，
     * 但它的锚点写的是「砖砌院墙里一排排石碑立在方座上」—— 那是露天的碑林，
     * 判成室内会把季节句和天空句一起退掉。**锚点是有人看过真地方写的，比名字规则可信。**
     */
    && !spotLook(scene.cityId, scene.spot)
    && spotProfile(scene.spot).indoor;

  /**
   * 这个点是不是在城区（只看地点本身，不看题材）—— 2026-11-15。
   *
   * 无 `spot` 时按「拍整座城」算，所以是城里；有 `spot` 时问类型；
   * 判不出（`setting === ''`）返回 `null`，调用方一律走老行为，**不猜**。
   */
  const spotSetting = scene.spot ? spotProfile(scene.spot).setting : '';
  const spotUrban: boolean | null = scene.spot
    ? (spotSetting === 'urban' ? true : spotSetting === 'wild' ? false : null)
    : true;
  /**
   * 这一张在城里还是野外 —— 见 `LightInput.urban`。
   *
   * 只给 `ground` 用：街景、食物、节日各有自己的模板，
   * 那些模板的照明句这次一个字没动（改动面要能一句话说清）。
   *
   * **室内不算城里。** 判成室内的点（博物馆展厅这类）站在屋里看不见
   * 「路面和楼里的窗」，套城市灯句只会更假 —— 这一支本就不该走到户外灯句上。
   */
  const urban = !sky && !scene.onRoad && !spotIndoor && spotUrban === true;

  const seasonText = (() => {
    if (closeup || sky || scene.onRoad || spotIndoor) return '';
    const full = trimScene(seasonLine(scene.cityId ? cityById(scene.cityId) : null, scene.month ?? 1));
    if (!full) return '';
    /*
     * 有日光：整段给（颜色也是内容）。没有日光的：只留存在物，见 `nightSeason`。
     *
     * **试过「超长就只留前三段」，被承德那条打回来了（2026-11-12 晚）。**
     * 承德十一月那句是六段：「…青砖灰调…；…开阔湖面…；…宫殿式大殿…；
     * …山峦古松…；**十一月末湖面已经冻成灰白冰板，冰上立着成片折断的褐色枯荷梗**；
     * …垂柳只剩细枝…」—— 「冰板 + 枯荷」正是这个季节最有辨识的一笔，恰好在第五段。
     * 砍段数就是砍辨识。**长度问题是真问题，但裁法不能靠段号。**
     */
    const base = sun.daylit ? full : nightSeason(full);
    /*
     * 城里要把「只有土路才成立」的那半句换掉（2026-11-15）。
     *
     * 西北十一月那条是「地面是干土，尘土浮在鞋面上」—— 兰州市区走在滨河路上，
     * 鞋上不该有土，路面也不是土的。这句写的是城外。
     */
    return urban ? citySeason(base, sun.daylit) : base;
  })();
  const withSeason = (base: string): string => {
    if (!seasonText) return base;
    const at = hardAnchorAt(base);
    if (at < 0) return base;
    return base.slice(0, at) + `${seasonText.replace(/。+$/, '')}。` + base.slice(at);
  };
  /*
   * 她正在做的那件事，先洗一遍（2026-11-08）。
   *
   * 引号必须去掉：`画面里没有文字` 那句约束挡不住「」里的字，
   * 模型会把台词当店招画出来。超过 40 字的截断 —— 提示词不是叙事的地方。
   */
  const doingNow = (() => {
    const t = String(scene.doing ?? '').replace(/[「」『』“”"]/g, '').replace(/\s+/g, ' ').trim();
    if (t.length < 4) return '';
    return t.length > 40 ? `${t.slice(0, 40)}…` : t;
  })();
  const withDoing = (base: string): string => {
    if (!doingNow) return base;
    const at = hardAnchorAt(base);
    const line = `正在发生的事：${doingNow.replace(/。+$/, '')}。`;
    return at < 0 ? `${base}${line}` : base.slice(0, at) + line + base.slice(at);
  };
  /*
   * 她自己补的那一句（2026-11-09）。
   *
   * 清洗规则跟 `doingNow` 一模一样，理由也一样：引号会被模型当招牌画出来，
   * 超长的描述会把这一格变成叙事。区别只有长度门槛 —— `doing` 写的是**发生的事**，
   * 四五个字才成句；`focus` 是**取景的补充**，「靠后坐」三个字就有用。
   */
  const focusNow = (() => {
    const t = String(scene.focus ?? '').replace(/[「」『』“”"]/g, '').replace(/\s+/g, ' ').trim();
    if (t.length < 2) return '';
    return t.length > 40 ? `${t.slice(0, 40)}…` : t;
  })();
  /*
   * **插在硬约束前面，不能追加到末尾。**
   *
   * 各条模板的最后一句都是「没有人物 / 没有文字」这类硬约束 ——
   * 模型对最后一句最敏感，把它挤到中间等于削弱它。
   *
   * 锚点要按优先级找：题材模板里有 `NO_PEOPLE`，而风景那条（ground）**没有这个常量**，
   * 它的末尾是「没有文字，没有水印，没有边框。」。第一版只找了 `NO_PEOPLE`，
   * 风景照就落到了最后一句后面 —— 测出来的正是这个。
   */
  const TAIL_RULE = '没有文字，没有水印，没有边框。';
  /*
   * 她自己写的那一句（2026-11-10）。清洗规则同 `focus`，长度放宽到 60 ——
   * 「看到什么」比「怎么拍」需要更多字：一个画面往往得点两样东西
   * （灯、猫、谁在看谁），40 字写不下。
   *
   * 上限定在 60 而不是无限：再长就变成她在写小说，事实层会被淹掉。
   */
  const describeNow = (() => {
    const t = String(scene.describe ?? '')
      .replace(/[「」『』“”"]/g, '')
      .replace(/\s+/g, ' ')
      .trim();
    if (t.length < 4) return '';
    return t.length > 60 ? `${t.slice(0, 60)}…` : t;
  })();

  const withFocus = (base: string): string => {
    if (!focusNow) return base;
    const line = `这一张想这么拍：${focusNow.replace(/。+$/, '')}。`;
    /*
     * **插在第一句之后，不再插在硬约束前面（2026-11-11）。**
     *
     * 原位置是「NO_PEOPLE 之前」—— 那是为了不把硬约束挤到中间（那个顾虑是对的），
     * 但代价是它排在一整串系统描述后面，等于白说。
     *
     * 「怎么拍」是用户自己写的意图，它该紧跟着「拍什么」。硬约束仍然在最后。
     */
    const firstStop = base.indexOf('。');
    const at = firstStop >= 0 ? firstStop + 1 : undefined;
    return at === undefined ? `${base}${line}` : base.slice(0, at) + line + base.slice(at);
  };
  /**
   * 她自己写的「画面里是什么」，插在标题句之后。
   *
   * 2026-11-12 之前只有风景那张用它 —— 于是「拍一下那个卖糖画的」，
   * 她写了 `describe`，食物和街景两条模板当没看见。**这是丢数据，不是风格问题。**
   */
  const withDescribe = (base: string): string => {
    if (!describeNow) return base;
    const line = `${describeNow.replace(/。+$/, '')}。`;
    const firstStop = base.indexOf('。');
    const at = firstStop >= 0 ? firstStop + 1 : undefined;
    return at === undefined ? `${base}${line}` : base.slice(0, at) + line + base.slice(at);
  };
  /*
   * **四个题材都要认 `describe`（2026-11-12 修）。**
   *
   * 原来只有 ground / sky 那一条拼了「她自己写的那句画面」，
   * 而 `ENV_PROMPT` 明明白白教她：他说「拍一下那个卖糖画的」，就写一句 `describe`。
   * 于是她照做了、提示词里却一个字都没有 —— 拍「晚饭」的时候那句永远丢掉。
   *
   * 现在六个题材共用同一条规则：**她写的画面紧跟在标题句之后**（人的意图优先），
   * 再是形制、天、光、季节、机位、硬约束。
   */
  if (subject === 'food') return withDescribe(withFocus(foodPrompt(scene)));
  if (subject === 'street') {
    return withDescribe(withFocus(withDoing(withSeason(streetPrompt(scene)))));
  }
  if (subject === 'festival') return withDescribe(withFocus(festivalPrompt(scene)));
  if (subject === 'detail') {
    return withDescribe(withFocus(withDoing(withSeason(detailPrompt(scene)))));
  }

  /*
   * 视觉锚点：把「这地方长什么样」补进提示词。
   *
   * 2026-11-04 之前这里只有地名（「九寨沟的甘海子」）。模型不认识「甘海子」，
   * 出来的是泛泛的暖金色高原湖。加上锚点之后就认得出是九寨沟了 ——
   * 同一句提示词、同一颗种子，唯一的差别就是这一串字。
   *
   * 路上的照片不加：那时候拍的是窗外掠过的田野村庄，套上"城市长什么样"
   * 反而会让它硬画一座城。
   */
  /*
   * 抬头拍天：`sky` 在上面已经判过了（季节和天空都要先问它一句）。
   */
  /*
   * **月份要传进去。**（2026-11-07）
   *
   * 锚点是「全年一句话」，里面可能写着「油菜花田成片明黄」；
   * 季节句是追加在它后面的 —— 两句话并存，模型两边都听，
   * 于是十一月拍出「银杏红枫 + 整片油菜花」。`vistaOf` 现在按花期摘句。
   */
  /*
   * 城市锚点也会跟天气打架：成都那句写死了「天空常罩一层灰白云」，
   * 晴天说它、半夜说它，都是假的。地理形制留着（街巷、老房），
   * 只把「天是什么颜色」这类气候断言在夜里和晴天摘掉。
   */
  // 第三个参数是「当前所在的景点」—— 锚点里提到它自己可以，提到同城别的景点就剔掉。
  /*
   * **景点自己的锚点优先（2026-11-11）。**
   *
   * 城市锚点一座城只有一条，清净寺和蟳埔村共用「红砖白石、燕尾脊、老榕」——
   * 画出来一模一样，而清净寺是花岗岩伊斯兰清真寺。
   * 命中 `SPOT_LOOK` 就整条换掉，不再叠加城市锚点。
   */
  const spotOwn = sky || scene.onRoad ? '' : spotLook(scene.cityId, scene.spot);
  const rawVista = sky || scene.onRoad ? ''
    : spotOwn || vistaOf(scene.cityId, scene.month, scene.spot);
  /*
   * 城市锚点里也藏着气候断言：「天空常罩一层灰白云」（成都）、「天常常是灰的」。
   * 原来只在夜里和晴天摘掉，阴天照样留着 —— 而阴天的天空现在由 `skyLine` 说，
   * 两句并存就是两个版本的同一片天。**一律摘掉。**
   */
  const vista = rawVista
    .replace(/，?天空常罩一层灰白云/g, '')
    .replace(/，?天常常是灰的/g, '');
  /*
   * 「敦煌的敦煌博物馆」—— 景点名里本来就带城市名时不要再加一遍（2026-11-11）。
   * 数据里这种不少（敦煌博物馆、西安城墙、苏州博物馆、上海博物馆…），
   * 之前每次都在提示词开头重复一次城市名，模型会当成两个地方。
   */
  const named = scene.spot
    ? (scene.spot.startsWith(scene.city) ? scene.spot : `${scene.city}的${scene.spot}`)
    : scene.city;

  const where = sky
    // 抬头拍天：取景方向变了，地点还在 —— 地面只留一道剪影，别让它抢戏。
    ? `${scene.city}上空，镜头抬起来对着天`
    : scene.onRoad
      /*
       * 路上的画面要说清「往外看」，不说模型就画一座城。
       * 带上交通方式是因为火车窗、汽车窗、机翼底下完全不是一回事。
       */
      /*
       * **夜里不说「田野、村庄和路」。**（2026-11-10 第三轮）
       *
       * 说了模型就得把这句画出来 —— 于是田永远是亮的、能看出绿的黄的。
       * 半夜在车窗里其实认不出那是田还是荒地，只认得出几个亮点。
       */
      ? (night
          ? `在${scene.mode ?? '车'}上往外看的窗外，${scene.city}一带的夜色`
          : `在${scene.mode ?? '车'}上往外看的风景，${scene.city}一带的田野、村庄和路`)
      /*
       * **有具体景点时，景点是画面主体，城市级描述退到「周围」（2026-11-11）。**
       *
       * 用户来信：「所有照片都是同一个特色建筑，不管在哪个景点都是这样……
       * 照片里全是当地特色建筑，然后景点的建筑看不到」。
       *
       * 查下来不在模型，在这句拼接：`vista` 是**城市级**的描述，而且**自带地标** ——
       * 昆明那句是「滇池水面开阔灰蓝，西岸西山陡壁拔起；石林灰黑石柱间长满绿草」，
       * 泉州那句是「……开元寺有石塔两座」，成都那句 40 个字里也全是「青瓦木构老房」。
       *
       * 原来拼成 `泉州的西街，红砖…开元寺有石塔两座…`：44 个字压着 4 个字的景点名，
       * 模型当然画开元寺。**景点名再准，也打不过一段更长的城市描述。**
       *
       * 现在把它显式降级成背景，主体先用一句话钉死。
       */
      /*
       * **有景点时，城市级描述整段不用（2026-11-11 第二版）。**
       *
       * 第一版是把它降级成「周围」——用户拿真模型验了一次，直接推翻：
       *
       *   「豆包我单独跑了，删除掉『周围红砖白石…开元寺有石塔两座，街巷榕树遮顶…』
       *     这段提示词，就能输出正常的照片。这段提示词有点意义不明，
       *     **我的鱼没去过开元寺，但每段提示词都会强调这个**。」
       *
       * 他说得对，而且比「权重压过景点」更严重：**这是编造**。
       * 她在清净寺，`vistaOf('quanzhou')` 却说「周围……开元寺有石塔两座」——
       * 模型忠实地把那座塔画进城，人看到的照片就永远是一座她没去过的寺。
       *
       * `vista` 是**城市级**的：它描述「这座城长什么样」，天生会带上城里的地标。
       * 只要她在某个具体景点，这句话里的地标就是别人的东西。
       *
       * 去掉它损失不了多少地域感 —— 季节句（`withSeason`）还在：
       * 「榕树樟树常绿，三角梅盛花」「地面干爽」「天空是饱和的蓝」都是按城市和月份算的。
       * 地点由景点说了算，气质由季节说了算，中间的「城市地标」这一层不要了。
       */
      /*
       * 锚点照常拼 —— 含同城**别的景点**的段已在 `vistaOf` 里剔掉了（2026-11-11）。
       *
       * 走过一版「有景点就整段不用」，能治编造，但把「像不像那地方」也一起治没了：
       * 九寨沟的钙化池、成都的青瓦木构全都没了。正确的位置在 `vistaOf` 里 ——
       * 剔的是专名，不是地貌。
       */
      /*
       * **有景点时，锚点降级成「周边一带」（2026-11-11，用户沃兔连续第三次来信）。**
       *
       * 他拍了两张：清净寺、蟳埔村。**提示词除了地名一个字都不差** ——
       * 因为锚点是城市级的，两个景点共用同一条「红砖白石、燕尾脊、老榕」。
       *
       * 更严重的是：清净寺是**花岗岩伊斯兰清真寺**（尖拱门、望月台、无燕尾脊），
       * 被套上「红砖厝燕尾脊」，画出来是一栋闽南民居。
       *
       * 他的原话最准：「她给我的文字信息是没错的，知道两个地点的差异，
       * 但是**写到提示词里就变成一样的了**。」
       *
       * 「周边一带是」这一句是划线：**景点本身由地名说了算，锚点只管周围环境**。
       * 模型至少不会再把这句当成「这个景点长这样」。
       *
       * 真正的解法是景点级锚点（一个景点一条），但 185 城 × 7 个景点 = 1300 条，
       * 而且「清净寺」这种名字靠规则分不出宗教类型。这条先止血。
       */
      /* 景点自己的锚点：直接描述这个景点，不加「周边一带」那层退让。 */
      : spotOwn
        ? `${named}，${spotOwn}`
      /*
       * 退回城市锚点：划线，说明那是周围环境而不是景点本身。
       *
       * **先判这个点是什么，再决定城市锚点里哪句能留（2026-11-14）。**
       *
       * 起因是 Mr.Q 一句「敦煌市明明是个市，敦煌博物馆却建在沙漠里，非常离谱」。
       * 查下来是这条路：敦煌博物馆没有专属锚点 → 退回敦煌的城市锚点
       * （「党河两岸窄绿洲…出城就是连片沙丘」）→ 一句「周边一带是」根本拦不住模型，
       * 它把沙丘一起画进了博物馆周边。
       *
       * 而这不是个例：`SPOT_LOOK` 只有 60 城 136 条，`CITIES` 是 185 城 × 3–9 个点，
       * 覆盖率约 15% —— **剩下 85% 全在这条路上**。代码注释里早写着这个死结
       * （「1300 条，这条先止血」），止血止不住。
       *
       * 所以不再往「一个点写一条」补。改判两件地点自身的事实：
       *   ① 类型（博物馆 / 石窟 / 关隘…）→ 决定室内还是野外
       *   ② 在城里还是野地 → 决定城市锚点里**哪几个分句根本不该出现**
       * 这两条不靠谁记得写，所以「博物馆旁边有沙丘」在结构上就不发生了。
       *
       * 形制（`p.form`）只在**她没写画面**时才补一句 —— 她写了就以她的为准。
       * 这是「以她看到的为主，系统只兜底」那条线，别倒过来。
       */
      : scene.spot
        ? (() => {
            const p = spotProfile(scene.spot);
            /*
             * **室内没有「周边一带」。** 站在展厅里看不见城外的平顶房和葡萄架。
             *
             * 实测过（2026-11-14，同种子两张）：只把沙丘剔掉、留着「周边一带：平顶房、
             * 白杨葡萄架夹着巷子」，出来仍然是一条村街 —— 模型在「室内，展柜和展墙」
             * 与「平顶房、巷子」之间选了后者，因为后者更长、更像一张旅行照片该有的景。
             * 句子之间不是平等的：**互相矛盾的描述里，写得多的那半边赢。**
             */
            const v = p.indoor ? '' : trimVistaFor(vista, p);
            const form = describeNow ? '' : p.form;
            const head = form ? `${named}，${form}` : named;
            /* 冒号不是句号：`周边一带是${v}` 会和锚点自己的「XX是…」撞出两个「是」。 */
            return v ? `${head}。周边一带：${v}` : head;
          })()
        : vista ? `${named}，${vista}` : named;
  /*
   * 光：**一个事实，一处宣布**（2026-11-12 重写）。
   *
   * 这里原来是五层嵌套三元 + 一张 `OVERCAST_LIGHT` 补丁表：
   * 先按钟点挑一句、天阴了再查表换一句、抬头拍天再换一句、末尾风格句又说「自然光」。
   * 四句话里三句在说光，于是成都 11 月 19 点那一版输出是这样的：
   *
   *     黄昏的金色光线。…天空是一整片灰白低云，没有太阳也没有影子…
   *     胶片质感，自然光，景深自然。…天色常是灰白的，看不见蓝天，也没有太阳。
   *
   * 「金色光线」和「没有太阳」在同一段里出现两次半。这不是措辞没调好，
   * 是**同一个事实被四个地方各说了一遍**。
   *
   * 现在只有一处：`lightLine()`。它拿到的唯一输入是太阳高度角和有没有云，
   * 输出的只有一句。季节句里的天空分句已经在 `trimScene` 里剥掉了，
   * 天气也只说「看得见什么」（雨丝、湿地面），不再说「阴」。
   */
  const light = sky
    /* 抬头那张的画面里没有地面照明可讲，天黑没黑由 `skyOf` 说。 */
    ? ''
    /* 展厅有自己的一句（2026-11-15）—— 室内点走到户外灯句上，等于让博物馆配路灯。 */
    : spotIndoor
      ? hallLight(sun)
      : lightLine({
        phase: sun.phase, overcast: sun.overcast, precip: sun.precip,
        indoor: false, whiteNight: sun.whiteNight, urban,
      });
  /** 天空那一句。特写没有天，抬头那张由 `skyOf` 说 —— 这里只管「地面以上的颜色」。 */
  /*
   * **室内不写天。** `spotIndoor` 这一条是 2026-11-14 加的：
   * 展厅里「天往浅里退，西边有一层薄云」是假的，而且它会把这句读成「户外」，
   * 跟「室内，展柜和展墙」打架 —— 打架的部分见 `where` 上面那段注释。
   */
  const skyTold = sky || closeup || spotIndoor
    ? ''
    : skyLine(sun.phase, sun.overcast, sun.precip, sun.whiteNight, urban);
  const lightFinal = light;

  /*
   * 风格分三档：
   * - 留空 → 原来的写实旅行照片（老行为，一个字没变）
   * - `none` → 一个字都不提风格，只描述场景，把画风完全交给底模
   * - 其他 → 用户给的原话当前缀
   *
   * 「没有人物/没有文字」这四不要**对任何风格都成立**，所以不在分支里。
   */
  const raw = (scene.style ?? '').trim();
  const bare = raw.toLowerCase() === 'none';
  const custom = raw !== '' && !bare;

  /*
   * 人物：留空就一个人都不画。
   *
   * 单独成句、不塞进 `where` 里 —— 塞进去会变成「一个穿风衣的女孩，九寨沟的五花海」，
   * 模型容易把人和景当成两个并列主体画成两张拼一起。分开说，人就是站在这个景里。
   */
  const cast = (scene.cast ?? '').trim();

  /*
   * 「写实照片」那一套词（真实旅行照片 / 胶片质感 / 路人视角）只在
   * **没人、也没指定风格**的时候加。
   *
   * 2026-11-04 实测的坑：设了二次元角色之后，出图还是写实风 —— 因为
   * 「一张真实旅行照片：」+「胶片质感，自然光」把 `anime style` 压过去了。
   * 风格是跟着人物走的，人物说了算，不该再被这几句拽回来。
   */
  const realism = !cast && !custom && !bare;
  const lead = bare ? '' : custom ? `${raw}：` : realism ? '一张真实旅行照片：' : '';

  /*
   * 抬头那张得先交代天上是什么。不交代的话，模型拿「城市名 + 夜色」会自己编一片星海，
   * 天阴着也照样画满天星——那就成了许愿，不是她抬头看见的东西。
   */
  /*
   * **经度和时区必须传进去**（2026-11-15）。不传的话 `skyOf` 按钟点算，
   * 而这一段的 `night` 是 `sceneSun()` 按太阳高度算的 —— 两套判据并存，
   * 喀什夏晚会出现「头顶满天星」和「胶片颗粒，轻微过曝」写在同一段里。
   */
  const skyInfo = sky
    ? skyOf(scene.hour, scene.weather ?? '', latNow, scene.month ?? 0,
        nowCity?.lon, nowCity?.tz, !scene.onRoad && spotUrban === true)
    : null;

  /*
   * 这个时节、这个地方，画面该是什么样（2026-11-07）。
   *
   * 起因是 Mr.Q 发来一张承德的图：零下二度，画出来是红灯笼 + 绿柳 + 湿石板 —— 江南意象。
   * 那时提示词里**没有一句说现在是冬天**，模型只能拿「承德 + 湖 + 园林」去联想。
   *
   * 拍天（sky）和在路上（onRoad）不加：前者只看天，后者的画面不属于某一座城。
   */
  /* 季节句在上面的 `seasonText` 里算过一次，这里直接用 —— 不许有第二套规则。 */
  const season = seasonText;
  /*
   * **回避句整条下线（2026-11-12）。**
   *
   * `avoidLine` 只给中国城市、只在冬半年返回一句，唯一还有内容的剩下川渝那条：
   * 「天色常是灰白的，看不见蓝天，也没有太阳」。
   *
   * 这句话现在有三重问题：
   *   1. 它和 `skyLine` 抢同一件事（天是什么颜色）；
   *   2. 它是**否定句**，而在生图模型上否定句常被读成强调 ——
   *      文件自己的注释里写着这个道理，这句却一直留着；
   *   3. 它排在**硬约束之后**（原来是倒数第二句）。模型对末句最敏感，
   *      等于让一句「天是灰的」压过「画面里没有人物」。
   *
   * 川渝冬天日照少是真的，但它该由 `skyLine` 用正面的话说：
   * 有云就说「天是一整片灰白的云」。**同一个事实，只说一次，说在它该在的位置。**
   */

  /*
   * 拼装顺序 = 权重顺序（2026-11-12 重排）：
   *
   *   人的意图（她写的画面 / 用户写的怎么拍）
   *   → 主体（在哪、这地方长什么样）
   *   → 天（有没有、什么颜色）
   *   → 光（地面被什么照着）
   *   → 季节（只看植被、地面、街头生活）
   *   → 事件（正在发生什么、体感）
   *   → 机位与质感
   *   → 硬约束（永远在最后，模型对末句最敏感）
   *
   * 两个「不许」：**天和光各只出现一次**；**叙述性的话不许挤到硬约束后面**。
   */
  const parts = [
    lead,
    /*
     * **她自己写的画面，是第一句（2026-11-11，Mr.Q：「后台提示词要给前端用户
     * 写入的提示词让路，前端为主后台做辅助」）。**
     *
     * 顺序就是权重。她说的放在 lead 后面第一句，系统那句退到第二句之后当环境。
     */
    describeNow ? `${describeNow.replace(/。+$/, '')}。` : '',
    `${where}。`,
    skyTold ? `${skyTold}。` : '',
    lightFinal ? `${lightFinal}。` : '',
    /*
     * 夜不是把白天的图调暗，夜是「看不见」。
     *
     * 这一句只补**形体**：颜色没了、只剩轮廓。不再重复「照不亮周围」——
     * 那是 `lightLine` 已经说过的话，说两遍不会更暗，只会让模型觉得这段在啰嗦。
     *
     * **展厅不写这句**（2026-11-15）：`skyTold` 在室内本来就被退掉，
     * 条件是恒真的，于是 `hallLight` 刚说完「顶灯和射灯照着展柜」，
     * 下一句就补「只剩轮廓」—— 两句正面打架。
     */
    night && !sky && !skyTold && !describeNow && !spotIndoor
      ? '其余部分看不出颜色，只剩轮廓。' : '',
    season ? `${season.replace(/。+$/, '')}。` : '',
    /*
     * **展厅里不写天气的后果**（2026-11-15）。
     * 「雪片在光里看得见，地上积了一层」是在街上说的；展厅里只有窗玻璃上的水。
     * 季节句和天空句都过了这道检查，这句原来漏了。
     */
    sun.precip && !spotIndoor ? `${weatherLine(sun.precip, sun.phase)}。` : '',
    /* 她正在做的事（2026-11-08）。先定场景，再说人。 */
    doingNow ? `正在发生的事：${doingNow.replace(/。+$/, '')}。` : '',
    cast ? `画面里有一个人：${cast}。` : '',
    skyInfo ? `头顶：${skyInfo.told}。` : '',
    /*
     * 「一道山脊剪影」原来是写死的 —— 成都是平原，画出来凭空长出一道山。
     * 只说「一道轮廓」，有山的地方模型会照着城市锚点补，没山的地方也不会硬编。
     */
    skyInfo ? '这一张以天空为主，地面只在最底下一道暗色轮廓。' : '',
    /*
     * `feel` 以句号结尾（`体感句。`），后面再拼「，画面能看出这一点」就成了「。，」——
     * 2026-11-09 在成都那张的提示词里实拍到了这个断句。模型不会因为一个逗号画错，
     * 但读的人一眼就知道这是拼接缝。
     *
     * ## 「画面能看出这一点」有个前提：体感得有视觉对应（2026-11-17，读者报的）
     *
     * 那位在哈尔滨想看雪，照片是一片枯黄平原。查下来不是 `bodyFeeling` 写死「冷」的问题 ——
     * `cold` 档那句「吸一口气鼻腔里就疼」本身没错，错在这句后面缀了「**画面能看出这一点**」：
     * 「干」有视觉对应（嘴唇、风），「潮」有（衣服、被子），**「冷」的视觉对应只有雪和白霜**。
     * 于是「冷」被单独翻译成「必须画冷的东西」，而那天天气是晴 —— 模型画了冬天却没雪，就是枯黄。
     *
     * 有天气数据时，画面该由天气决定，体感只是她的感受；没有天气才退到体感。
     */
    scene.feel
      ? `${String(scene.feel).replace(/[。．.！!？?，,；;、\s]+$/, '')}，`
        + (scene.weather ? '这是她的体感，画面里的天气以上面那句为准。' : '画面能看出这一点。')
      : '',
    /*
     * 机位压短（2026-11-11）。「视角自然随意，略微不完美，有生活感」十七个字，
     * 对模型只有「不要摆拍」这一个意思，五个字够。
     */
    realism ? '随手拍。' : '',
    realism
      /*
       * **尾句不再出现「自然光」。**（2026-11-12）
       *
       * 「自然光」是个总体判断词，权重又排在最后，会把前面算出来的
       * 深夜、黄昏、蓝调全部推翻。现在只留质感。
       *
       * **拍了星的那张不能写「手机夜拍、噪点明显」**（2026-11-15）。
       * 同一段前面刚说「满天星，银河斜过天顶」，末尾却说手持噪点、暗部没细节 ——
       * 银河会被糊成一片灰。长曝是星空唯一拍得出来的方式。
       */
      ? (sky && skyInfo?.stars
          ? '三脚架长曝，星点很实，暗部干净。'
          : sun.whiteNight
            ? '胶片颗粒，光偏白，暗部还看得清。'
            : sun.daylit ? '胶片颗粒，轻微过曝。' : '手机夜拍，噪点明显，暗部没有细节。')
      : '',
    // 有人和没人，这两句不能并存 —— 同一段提示词里既说有人又说没人，出图会飘。
    /*
     * 风景照也留人气 —— 一个人都没有的古城是置景，不是有人住的地方。
     * 但**拍天那张不能有人**：镜头朝天，画面里只有天和地平线一道轮廓。
     */
    cast ? '画面里只有这一个人，不要出现其他人。'
      : sky ? `${NO_PEOPLE}。`
      /*
       * 展厅里的人叫观众，不叫行人（2026-11-15）。
       * 「远处散着几个很小的行人」是在街上说的 —— 套进展厅，模型会顺手给展柜配一条街。
       */
      : spotIndoor ? '远处有几个观众，背对着镜头，看不清脸。'
      /*
       * **试过给 `wild` 也配「没有人」，被 `photo-subject` 打了回来**：
       * 婺源的江岭判成 mountain / wild，可那是有人住的梯田村。
       * 「不在市区」推不出「没有人」，这条判据撑不住 —— 宁可留着人气。
       */
      : `${FAR_PEOPLE}。`,
    '没有文字，没有水印，没有边框。',
  ];
  return withFocus(parts.filter(Boolean).join(''));
}

/** 抬头那一眼能看见什么。`told` 进提示词，`stars` 进回执。 */
export interface SkyView {
  readonly told: string;
  /** 这一眼有没有星。她要星空时，回执拿它说实话。 */
  readonly stars: boolean;
}

/**
 * 抬头那一眼。**只看小时和天气，不看他要什么。**
 *
 * 这是「拍天空」和「许愿画图」的分界线：他要星空，天阴着就还是云；
 * 他要月亮，正午就是蓝天。给的是她真的看得见的那片天 ——
 * 否则她「拍到了星空」这件事本身就是假的，一查天气就露。
 */
export function skyOf(
  hour: number, weather: string, lat = 0, month = 0, lon?: number, tz?: string,
  /**
   * 这一眼是在城里抬的（2026-11-15）。判据同 `LightInput.urban`。
   *
   * 光污染把暗星全吃掉：市区晴夜看不到银河，只剩最亮的一两颗。
   * 不判这一条，兰州城关、上海、东京的晴夜全给「满天星」，回执还会跟着说
   * 「拍到了星空」—— 那是**两头都在撒谎**：图上没有，话里说有。
   */
  urban = false,
): SkyView {
  const h = ((hour % 24) + 24) % 24;
  const m = month > 0 ? month : 1;
  /*
   * 全天三个时刻的太阳高度：此刻、正午、午夜。
   *
   * 只看此刻是不够的 —— 「这一夜到底黑不黑」问的是**午夜**那一刻，
   * 「正午太阳上不上得来」问的是正午。极昼、极夜、白夜这三种现象
   * 都是这两个边界值的结果，不需要再单独列纬度表。
   */
  const altNow = sunAltitude(lat, m, h, lon, tz);
  const altNoon = sunAltitude(lat, m, 12, lon, tz);
  const altMid = sunAltitude(lat, m, 0, lon, tz);

  /*
   * 云分两档，别一刀切。
   *
   * 「阴」是整片盖住，一颗都不透；「多云」在真实夜里是能看见亮星的 ——
   * 尤其九寨沟这种光污染低的地方。把多云也判成没星，等于让一个明明能看见星的地方
   * 说「看不见」，那也是另一种不真，而且是最伤人的那种：当着满天云缝说没星。
   */
  const w = String(weather ?? '');
  const heavy = /阴|雨|雪|雾|雷|霾|沙|尘/.test(w);
  const partly = !heavy && /云/.test(w);

  /* 极夜：正午太阳也不上来。摩尔曼斯克十二月就是这一档。 */
  if (altNoon < 0) {
    return { told: '正午太阳也没上来，天是一层深蓝的暮光，地平线泛一点灰白', stars: false };
  }
  /* 极昼：午夜太阳都不落。漠河夏至前后整夜不黑。 */
  if (altMid > -1) {
    return { told: '天一直亮着，太阳贴着地平线绕，天边是灰白的', stars: false };
  }
  /* 白夜：半夜天不黑透，只有最亮的那几颗。 */
  if (altMid > -10 && !phaseIsDaylit(sunPhase(altNow))) {
    return {
      told: partly
        ? '天没黑透，北边还留着一层灰蓝，云缝里有几颗最亮的星'
        : '天没全黑，北边一直留着一层灰蓝，只有几颗最亮的星',
      stars: true,
    };
  }

  switch (sunPhase(altNow)) {
    case 'night':
      if (heavy) return { told: '夜里，云层压得很低，一颗星都不透', stars: false };
      if (partly) return { told: '夜里，云占了大半，云缝里漏出几颗亮的', stars: partly && !urban };
      /*
       * 城里那一版同时把 `stars` 改成 false —— 回执拿它说「拍到了星空」，
       * 只看得到一两颗的夜空不算星空。**图和话必须一起改**，只改图是半修。
       */
      return urban
        ? { told: '夜里，天是深灰的，被底下的灯映亮，只看得见一两颗星', stars: false }
        : { told: '夜里，满天星，银河斜过天顶，暗处都看得清', stars: true };
    case 'twilight':
      if (heavy) return { told: '天边只剩一线灰蓝，被云压得更暗了', stars: false };
      return { told: '天边只剩一线灰蓝，上面已经黑，先出来几颗亮的', stars: true };
    case 'blue':
      if (heavy) return { told: '天是压着云的深蓝，一颗星也看不见', stars: false };
      return {
        told: partly ? '天是饱和的深蓝，云缝里有一两颗星' : '天是饱和的深蓝，最早那几颗星已经出来',
        stars: true,
      };
    case 'afterglow':
      if (heavy) return { told: '太阳落下去了，云把最后一点光挡了', stars: false };
      return { told: '太阳刚落，天边橙红压着一层蓝，还没有星', stars: false };
    case 'golden':
      if (heavy) return { told: '太阳在云后面，天边只剩一点暖色', stars: false };
      return { told: '太阳贴着地平线，天边是最浓的橙', stars: false };
    default:
      if (heavy) return { told: '阴天，云层很厚，看不见太阳的边', stars: false };
      if (partly) return { told: '多云，太阳在云后面时隐时现', stars: false };
      return { told: '晴，蓝天和几朵散云', stars: false };
  }
}

/**
 * 从作息节点的一句话里抠出地点。
 *
 * 节点写的是「下午，莫高窟」「清晨，老城那几条街」—— 前半截是时段，后半截才是地方。
 * 抠不出来就返回空串，让调用方只写城市名：**宁可能说的少，不要编一个地点**。
 */
export function spotFromBeat(what: string): string {
  const m = /[，,]\s*(.+)$/.exec(what.trim());
  const spot = (m?.[1] ?? '').trim();
  // 「城里随便走走」这种不是地点，别塞进提示词让模型去画一座「随便走走」。
  if (!spot || /随便走走|走一段|坐着看水|视野开的那一段|沿着水边/.test(spot)) return '';
  return spot.replace(/。$/, '');
}

/**
 * 这张照片叫什么。给相册用，一句话，不加书名号。
 *
 * 时间要参与命名：同一座城市不同时候拍出来是两张不同的照片，
 * 都叫「天水」的话相册里会有一排同名。
 */
export function photoTitle(
  city: string, spot: string, hour: number, view: 'ground' | 'sky' = 'ground',
  /**
   * 拍的是什么（2026-11-06 补）。
   *
   * 标题是回执里**唯一能对她说的事实**（`takePhotoForUser` 只喂她标题，
   * 不给她图）。标题不认题材，就会出现「她拍了碗面，回执说黄昏的巷子」，
   * 然后她照着这句错话跟他描述——比不拍更糟。
   */
  subject: PhotoSubject = 'ground',
): string {
  /*
   * 拍了什么就说什么，一句都不多。
   *
   * 这里只做**命名**，不做推断：不写菜名（菜名在 `pickFood` 里按城市和时段挑，
   * 这一层拿不到，硬写就得编），不写天晴还是下雨，不写画里有什么。
   */
  if (subject === 'food') {
    /*
     * 按时刻分几顿，不细分——她是人，不会说「下午茶用了 47 分钟」。
     *
     * **凌晨不能叫早饭**（2026-11-13，mrlin97 在 Discussion #586 实测）：
     * 当地 01:06 拍 subject=food，回执写「成都的早饭，当地 1 点」。
     * 原来第一档是 `hour < 10 ? '早饭'`，把 0–10 点整段吞了进去。
     * 图没错，错的是这两个字 —— 凌晨一点不可能是早饭。
     *
     * 分档改成：0–5 宵夜、5–10 早饭、10–15 午饭、15–17 晌午、17–21 晚饭、21–24 宵夜。
     * 顺带把钟点归一：调用方给的是当地小时，正常不会越界，但 `photoTitle` 是纯函数，
     * 别人拿 25 或 -1 来调也得给个说得通的词（天空那支本来就是这么处理的）。
     */
    const h = ((hour % 24) + 24) % 24;
    const meal = h < 5 ? '宵夜'
      : h < 10 ? '早饭'
      : h < 15 ? '午饭'
      : h < 17 ? '晌午的饭'
      : h < 21 ? '晚饭'
      : '宵夜';
    return `${spot || city}的${meal}`;
  }
  if (subject === 'street') return `${spot || city}的街`;
  if (subject === 'detail') return `${spot || city}的一处细节`;
  /* 时节，不是节气——节气是日历上那一天，她这会儿看到的是这一段。 */
  if (subject === 'festival') return `${spot || city}的这个时节`;
  /*
   * 抬头那张的标题不写「星空」写「夜空」。
   *
   * 标题是纯函数，拿不到天气；天阴着还标「星空」就是替她撒谎。
   * 「夜空」在晴和阴两种天里都成立 —— 宁可含糊，不写假话。
   */
  if (view === 'sky' || subject === 'sky') {
    const h = ((hour % 24) + 24) % 24;
    const part =
      h >= 20 || h < 4 ? '夜空'
      : h < 7 ? '天光'
      : h < 17 ? '天空'
      : h < 19 ? '晚霞'
      : '暮色';
    return `${spot || city}的${part}`;
  }
  const part =
    hour < 9 ? '清晨'
    : hour < 12 ? '上午'
    : hour < 15 ? '午后'
    : hour < 18 ? '下午'
    : '黄昏';
  return spot ? `${part}的${spot}` : `${part}的${city}`;
}

/**
 * 调一次生图。
 *
 * 支持两种返回：`b64_json`（OpenAI 与多数兼容接口）和 `url`（一部分服务，含火山方舟）。
 * 两种都要，因为「兼容」这两个字在现实里只兼容到一半。
 *
 * ## 失败要吵，成功要静
 *
 * 这个函数**抛错**，不返回 null。区别很大：返回 null 只能让上层记一句「没拍成」，
 * 而用户真正需要知道的是「HTTP 401：密钥无效」还是「HTTP 400：size 不支持」。
 * 上层 `maybePhoto` 会 catch 住并且只写日志 —— 旅行一步都不停，但日志里得有原因，
 * 否则用户配错了永远不知道为什么相册是空的。
 *
 * ## size 的重试
 *
 * 字段名和取值在不同服务上都不一样，实测三种：
 *
 * - OpenAI / 火山方舟：`size`（`1024x1024` / `2K`）
 * - 硅基流动、阿里百炼那种 DashScope 血统的：**`image_size`**，传 `size` 直接 400
 * - 有的干脆只认自己模型的默认尺寸，多传一个就报错
 *
 * 所以分两步退：先按 OpenAI 的写法发；400 且错误里点名 `image_size` 就换字段名重发
 * （尺寸不变）；还是不行才整个去掉，让服务商用默认值。
 * 判据是**错误文本**，不是状态码 —— 三种情况的 400 长得一模一样。
 */
/**
 * 从「must be one of: …」这种报错里挖出候选尺寸，挑一个和目标**宽高比最接近**的。
 *
 * ## 为什么要有这一步
 *
 * 各家的尺寸枚举完全不同，而且都会报错：
 *
 * - Qwen-Image / Z-Image：认 `1664x928` 这种任意值
 * - **MOSS-Image**：只认 8 个固定档 —— `1024x1024(1:1) 832x1216(2:3) 1216x832(3:2)
 *   896x1152(3:4) 1152x896(4:3) 768x1344(9:16) 1344x768(16:9) 1568x672(21:9)`，
 *   而且**必填**
 *
 * 2026-11-04 用户换成 MOSS 就直接 400，而错误文案里其实已经把 8 个候选全列出来了。
 * 让用户为每个模型查一遍规格是不现实的 —— 那就自己读、自己挑。
 *
 * 挑的判据是**宽高比的距离**，不是"取最长边最接近的"：16:9 的 `1664x928` 要挑到
 * `1344x768`（16:9），而不是像素数更接近的 `1568x672`（21:9）——
 * 后者会让画面横向拉长，构图整个变了。
 */
export function nearestSize(errText: string, want: string): string | null {
  const tail = /must be one of[：:]\s*([\s\S]+)/i.exec(errText)?.[1] ?? '';
  const cands = [...tail.matchAll(/(\d{2,5})\s*[x×*]\s*(\d{2,5})/gi)].map((m) => `${m[1]}x${m[2]}`);
  if (!cands.length) return null;

  const w = /(\d{2,5})\s*[x×*]\s*(\d{2,5})/i.exec(want ?? '');
  if (!w) return cands[0];
  const target = Number(w[1]) / Number(w[2]);
  if (!Number.isFinite(target) || target <= 0) return cands[0];

  let best = cands[0];
  let bestDiff = Infinity;
  for (const c of cands) {
    const [cw, ch] = c.split('x').map(Number);
    const diff = Math.abs(cw / ch - target);
    if (diff < bestDiff) { bestDiff = diff; best = c; }
  }
  return best;
}

/**
 * 模型名填错时，问服务端「你这儿有哪些模型」，给他指到该填哪一个。
 *
 * 拿不到列表就返回 null —— 照常报原来的错，不因为「提示失败」把流程带歪。
 */
async function modelNameHint(base: string, key: string, want: string): Promise<string | null> {
  /*
   * 带 `type=image` 问，只列图片模型 —— 不然硅基流动会返回近百个文本模型
   * （DeepSeek、GLM 之类），对"我该填哪个画图模型"这个问题毫无帮助。
   * 不认这个参数的服务退回去问全部，总比没有强。
   */
  const askList = async (query: string): Promise<string[]> => {
    const res = await fetch(`${base}/models${query}`, {
      headers: key ? { authorization: `Bearer ${key}` } : {},
      signal: AbortSignal.timeout(8000),
    });
    if (!res.ok) return [];
    const body = (await res.json().catch(() => null)) as { data?: { id?: unknown }[] } | null;
    return (body?.data ?? [])
      .map((m) => m.id)
      .filter((id): id is string => typeof id === 'string' && id.length > 0);
  };
  try {
    let ids: string[] = [];
    try { ids = await askList('?type=image'); } catch { /* 下面还有一次机会 */ }
    if (!ids.length) ids = await askList('');
    if (!ids.length) return null;

    // 拿他填的那一截（去掉可能带的厂商前缀）去模糊匹配
    const tail = want.trim().toLowerCase().split('/').pop() ?? '';
    const guess = tail ? ids.filter((id) => id.toLowerCase().includes(tail)) : [];

    const lines = [
      `模型名对不上：「${want.trim() || '(空)'}」服务端没有这个模型。`,
      '这类服务的模型 ID 要带厂商前缀，写成「厂商/模型名」，比如 Tongyi-MAI/Z-Image-Turbo。',
    ];
    if (guess.length) lines.push(`你要的应该是：${guess.join(' 或 ')}`);
    const shown = ids.slice(0, 12).join('、');
    lines.push(`服务端现在有的：${shown}${ids.length > 12 ? ` 等 ${ids.length} 个` : ''}`);
    return lines.join('\n');
  } catch {
    return null;
  }
}

export async function shootPhoto(req: PhotoRequest): Promise<PhotoBytes> {  const base = req.api.trim().replace(/\/+$/, '');
  if (!base) throw new Error('生图接口没填');

  const url = `${base}/images/generations`;
  const body: Record<string, unknown> = {
    model: req.model?.trim() || PHOTO_MODEL,
    prompt: req.prompt,
    /*
     * `n` 不写在 body 里，改由 `withN` 控制（2026-11-14）。
     *
     * 火山方舟的图片接口**根本没有 n 这个参数**（只有 `sequential_image_generation`），
     * 而豆包是这次新接的一条路。我们只出一张，本来就不必发它 ——
     * 但有些中转服务要求这个字段，所以默认照发、400 时摘掉。
     */
    // 有的服务只认 response_format，有的根本不认这个字段（认不认都不会报错）。
    response_format: 'b64_json',
  };
  const headers: Record<string, string> = { 'content-type': 'application/json' };
  if (req.key.trim()) headers.authorization = `Bearer ${req.key.trim()}`;
  const timeout = req.timeoutMs ?? PHOTO_TIMEOUT_MS;

  const send = (payload: Record<string, unknown>): Promise<Response> =>
    fetch(url, {
      method: 'POST',
      headers,
      body: JSON.stringify(payload),
      signal: AbortSignal.timeout(timeout),
    });

  const wantSize = req.size?.trim() || PHOTO_SIZE;
  /*
   * 实际发出去的尺寸。可能被下面的重试改掉 —— 有些模型只认固定枚举
   * （见 `nearestSize` 的注释），换成一个同样比例、它认的值。
   */
  let sizeValue = wantSize;

  /*
   * 尺寸怎么写、要不要 `response_format`，各家不同。用三个开关描述「这一版请求长什么样」，
   * 每次 400 只改一个 —— 改哪一个是**看错误文本**决定的，不是按顺序瞎试。
   */
  let sizeField: 'size' | 'image_size' | null = 'size';
  let withFormat = true;
  /** 发不发 `n`。方舟不认，服务商报 400 时摘掉。 */
  let withN = true;
  /*
   * 默认请求「不要水印」。
   *
   * 2026-11-01 实测：硅基流动的免费模型（Kolors）默认在右下角烧一个「AI 生成」，
   * 提示词里写「没有水印」没用 —— 那是平台加的，不是模型画的。
   * 这一句是参数，不是描述。不认识这个字段的服务会 400，那就按阶梯去掉。
   */
  let withWatermark = true;
  const build = (): Record<string, unknown> => {
    const payload: Record<string, unknown> = { ...body };
    if (withN) payload.n = 1;
    if (!withFormat) delete payload.response_format;
    if (withWatermark) payload.watermark = false;
    if (sizeField) payload[sizeField] = sizeValue;
    return payload;
  };

  let res: Response;
  try {
    res = await send(build());
    /*
     * 最多再试两次。不追组合爆炸：真要两种字段一起被挑，让它报错进日志，
     * 比连发五六次把人家的限速打满强 —— 这个功能一天最多一张，不值得为它烧配额。
     */
    for (let i = 0; i < 3 && res.status === 400; i++) {
      const peek = (await res.clone().text()).slice(0, 400);
      const before = `${sizeField}|${withFormat}|${withWatermark}|${withN}|${sizeValue}`;
      if (/image_size/i.test(peek) && sizeField !== 'image_size') {
        // 硅基流动、阿里百炼那一支：只认 image_size，传 size 直接拒
        sizeField = 'image_size';
      } else if (sizeField && /must be one of/i.test(peek)) {
        /*
         * 字段名对了、**值**不在它认的枚举里。2026-11-04 MOSS-Image 就是这样：
         *
         *   image_size must be one of: 1024x1024 (1:1), 832x1216 (2:3), 1216x832 (3:2),
         *   896x1152 (3:4), 1152x896 (4:3), 768x1344 (9:16), 1344x768 (16:9), 1568x672 (21:9)
         *
         * 而配置里填的是 1664x928（Qwen-Image 的规格）。每个模型的枚举都不一样，
         * 让用户挨个记是不现实的 —— **错误信息里已经把候选列出来了**，直接挑一个。
         */
        const alt = nearestSize(peek, sizeValue);
        if (alt) sizeValue = alt;
        else sizeField = null;   // 连候选都解析不出来，只能退回默认尺寸
      } else if (withN && /(^|[^a-z])n([^a-z]|$)|num_images|batch/i.test(peek)) {
        /* 不认 `n` 的服务（火山方舟就是）：摘掉，反正只要一张。 */
        withN = false;
      } else if (/response_format/i.test(peek) && withFormat) {
        // 不认识这个字段的服务：去掉它，回头看 data[0].url 也能取图
        withFormat = false;
      } else if (/watermark|水印/i.test(peek) && withWatermark) {
        // 不认识这个字段的服务：去掉，把那一点点水印忍了
        withWatermark = false;
      } else if (/size|尺寸|分辨率/i.test(peek) && sizeField !== null) {
        // 尺寸值本身它不收：什么尺寸都不带，让它用自己的默认值
        sizeField = null;
      }
      if (`${sizeField}|${withFormat}|${withWatermark}|${withN}|${sizeValue}` === before) break;   // 认不出该改什么，别乱试
      res = await send(build());
    }
  } catch (e) {
    const name = e instanceof Error ? e.name : 'Error';
    throw new Error(name === 'TimeoutError' ? '超时了' : `连不上服务（${name}）`);
  }

  if (!res.ok) {
    const detail = await readError(res);
    /*
     * 模型名不存在 —— 单独说清。
     *
     * 2026-11-04 Mr.Q 填了 `Z-Image`，日志里连着三条
     * `HTTP 400：Model does not exist`。真正的原因是**少了厂商前缀**：
     * 硅基流动的模型 ID 是 `厂商/模型名`（`Tongyi-MAI/Z-Image-Turbo`），
     * 只写 `Z-Image` 它当然找不到。
     *
     * 这种错光看报错是猜不出来的 —— 用户会以为自己填的名字服务端不支持，
     * 然后一个个试。既然是模型名的问题，就把**能用的名字列出来**，
     * 再按他填的那截做一次模糊匹配，直接指到该填哪一个。
     */
    if (/model.*(not exist|not found|does not)/i.test(detail)) {
      const hint = await modelNameHint(base, req.key, req.model ?? '');
      if (hint) throw new Error(hint);
    }
    throw new Error(`服务返回 HTTP ${res.status}${detail ? `：${detail}` : ''}`);
  }

  /*
   * **不用 res.json()。** 它把 JSON.parse 的真实原因吞掉，只剩一句「不是 JSON」——
   * 2026-11-01 收到一条反馈：中转站那边图生成成功，这边只报「返回的不是 JSON」，
   * 用户和我们都没法判断是格式坏了、被截断了、还是返回了别的东西。
   * 改成先拿原文，失败时把大小、原始错误、头尾片段一起带出去。
   */
  const raw = await res.text();
  let payload: unknown;
  try {
    payload = JSON.parse(raw);
  } catch (e) {
    const repaired = repairJsonText(raw);
    if (repaired === null) throw new Error(badJsonDetail(raw, e));
    payload = repaired;
  }

  const first = firstImage(payload);
  if (!first) throw new Error('返回里没有图');

  if (typeof first.b64_json === 'string' && first.b64_json.length > 0) {
    const bytes = new Uint8Array(Buffer.from(first.b64_json, 'base64'));
    /*
     * 用文件头认格式，**别硬写 image/png**。
     *
     * 两个理由：中转站给的也可能是 JPEG，写死 PNG 扩展名就错了；
     * 更要紧的是 —— 有些中转站在日志/响应里把 b64 换成占位符
     * （「[base64 image data omitted]」这种），解出来根本不是图。
     * 那种情况下必须当场说清，否则会存成一张打不开的「照片」。
     */
    const mime = sniffImage(bytes);
    if (!mime) {
      const head = Buffer.from(bytes.slice(0, 16)).toString('hex');
      throw new Error(`b64 解出来不是图片（前 16 字节 ${head || '空'}）—— 中转站可能返回了占位符或截断的数据`);
    }
    return { bytes, mime };
  }
  if (typeof first.url === 'string' && /^https?:\/\//.test(first.url)) {
    try {
      const dl = await fetch(first.url, { signal: AbortSignal.timeout(timeout) });
      if (!dl.ok) throw new Error(`下载图片 HTTP ${dl.status}`);
      const buf = new Uint8Array(await dl.arrayBuffer());
      if (!buf.length) throw new Error('图片是空的');
      const header = dl.headers.get('content-type')?.split(';')[0]?.trim().toLowerCase() ?? '';
      /*
       * **不能只信 content-type。** 对象存储（阿里 OSS、各家 CDN）很常见地把图片标成
       * `application/octet-stream` 或者压根不给。宿主按 mime 决定落盘扩展名，
       * 认不出就存成 `.bin` —— 用户双击打不开，相册也显示不出来
       * （2026-11-01 真实发生：一张 1.7MB 的 PNG 存成了 4aeaca….bin）。
       *
       * 所以：给的是 image/* 就用它；否则**看文件头**，再不行才按 PNG。
       */
      const mime = header.startsWith('image/') && !header.includes('octet-stream')
        ? header
        : sniffImage(buf) ?? 'image/png';
      return { bytes: buf, mime };
    } catch (e) {
      throw new Error(`拿到了图片地址但下载失败（${e instanceof Error ? e.message : '未知'}）`);
    }
  }
  throw new Error('返回格式不对：既没有 b64_json 也没有 url');
}

/**
 * 中转站常见的一种坏法：base64 里带着**裸换行**（没转义成 \n）。
 * 那不是合法 JSON，但把字符串内部的换行吃掉就能解析。
 *
 * 只在 JSON.parse 失败后才试，而且只动 base64 那一段 ——
 * 别处的换行删了会改变内容（提示词里的换行是有意义的）。
 */
function repairJsonText(raw: string): unknown | null {
  /*
   * 盯住 b64_json 那个值，把它内部的空白全删掉。
   * base64 不含空白字符，所以这个动作是安全的；而按长度猜断行位置不可靠
   * （最后一段可能只有十几个字符，写死阈值就漏）。
   */
  /*
   * **用 lookahead 卡后面的分隔符，别把它吃进匹配里。**
   * 写成 `"\s*[,}]` 的话 m[0] 会带上那个 `}`，替换之后 JSON 少一个括号，
   * 修完还是不合法 —— 第一版就是这么错的。
   */
  const m = raw.match(/"b64_json"\s*:\s*"([\s\S]*?)"(?=\s*[,}])/);
  if (!m) return null;
  const cleaned = m[1].replace(/\s+/g, '');
  if (cleaned === m[1]) return null;
  // 用函数形式替换：值里可能有 `$`，字符串形式替换会被当成特殊记号。
  const rebuilt = raw.replace(m[0], () => `"b64_json":"${cleaned}"`);
  try {
    return JSON.parse(rebuilt);
  } catch {
    return null;
  }
}

/** 把长 base64 串折成占位，别把几 MB 的图塞进日志和界面。 */
function maskBase64(text: string): string {
  return text.replace(/[A-Za-z0-9+/=]{80,}/g, (m) => `<base64 ${m.length} 字符>`);
}

/** 解析失败时能让人判断到底怎么了：多大、原始错误、头尾长什么样。 */
function badJsonDetail(raw: string, err: unknown): string {
  const why = err instanceof Error ? err.message : String(err);
  const head = maskBase64(raw.slice(0, 160));
  const tail = maskBase64(raw.slice(-40));
  const look = raw.length > 200 ? `开头 ${head} … 结尾 ${tail}` : head;
  return `返回的不是 JSON（${raw.length} 字符）：${why}。${look}`;
}

/**
 * 从返回体里捞出第一张图。
 *
 * **不能只认 `data`。** 2026-11-01 同一天里两种形状都见着了：
 * OpenAI 与多数兼容层是 `{ data: [{ url }] }`，硅基流动现在回的是
 * `{ images: [{ url }] }` —— 只认 `data` 的话，图明明生成好了，
 * 这边却报「返回里没有图」，钱照扣。
 */
export function firstImage(payload: unknown): { b64_json?: unknown; url?: unknown } | undefined {
  if (!payload || typeof payload !== 'object') return undefined;
  const o = payload as Record<string, unknown>;
  // 顶层直接给一个地址的服务也见过
  if (typeof o.url === 'string') return { url: o.url };
  for (const key of ['data', 'images', 'output', 'outputs', 'result']) {
    const list = o[key];
    if (!Array.isArray(list) || !list.length) continue;
    const first = list[0];
    if (typeof first === 'string') return /^https?:\/\//.test(first) ? { url: first } : undefined;
    if (first && typeof first === 'object') return first as { b64_json?: unknown; url?: unknown };
  }
  return undefined;
}

/**
 * 按文件头认图片格式。认不出返回 null。
 *
 * 只认这四种：这个功能产出的就是这四种，别的一律当 PNG 处理 —— 反正后面要交给宿主，
 * 猜错扩展名比认不出来更糟。
 */
export function sniffImage(bytes: Uint8Array): string | null {
  const b = bytes;
  if (b.length >= 8 && b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return 'image/png';
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return 'image/jpeg';
  if (b.length >= 6 && b[0] === 0x47 && b[1] === 0x49 && b[2] === 0x46) return 'image/gif';
  if (
    b.length >= 12 && b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46
    && b[8] === 0x57 && b[9] === 0x45 && b[10] === 0x42 && b[11] === 0x50
  ) return 'image/webp';
  return null;
}

/**
 * 这张图到底多大（像素）。认不出返回 null。
 *
 * ## 为什么要量
 *
 * 2026-11-12 用户反馈：「我填 1664x1244，静默变成 1024x1024，白等一轮。」
 * 服务商不认这个尺寸时不会报错，直接按自己的默认值出图 —— 请求是对的、图也回来了，
 * 只是**不是他要的那张**。他不看日志就永远不知道问题出在尺寸上。
 *
 * 只认 PNG 和 JPEG 两种：这两家占了几乎所有出图接口。GIF/WebP 不认，
 * 返回 null 就是不量，不影响出图。
 */
export function imagePixelSize(bytes: Uint8Array): readonly [number, number] | null {
  try {
    /* PNG：签名 8 字节，紧跟 IHDR（长度 4 + 类型 4），宽高各 4 字节大端。 */
    if (bytes.length >= 24 && bytes[0] === 0x89 && bytes[1] === 0x50) {
      const v = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
      return [v.getUint32(16), v.getUint32(20)];
    }
    /*
     * JPEG：从 SOI 开始逐段跳。SOF0/1/2（0xC0–0xC2）里才有宽高 ——
     * 段结构是 FFxx + 长度(2) + 数据，长度含它自己那两字节。
     */
    if (bytes.length >= 4 && bytes[0] === 0xff && bytes[1] === 0xd8) {
      let i = 2;
      while (i + 9 < bytes.length) {
        if (bytes[i] !== 0xff) { i += 1; continue; }
        const marker = bytes[i + 1];
        if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) { i += 2; continue; }
        const len = (bytes[i + 2] << 8) | bytes[i + 3];
        if (len < 2) return null;
        if (marker >= 0xc0 && marker <= 0xc2) {
          const h = (bytes[i + 5] << 8) | bytes[i + 6];
          const w = (bytes[i + 7] << 8) | bytes[i + 8];
          return [w, h];
        }
        i += 2 + len;
      }
    }
    return null;
  } catch {
    return null;
  }
}

/**
 * 从错误响应里捞一句人能看懂的。
 *
 * 各家的错误结构不一样：OpenAI 是 `{error:{message}}`，方舟是 `{error:{message}}` 或
 * `{message}`，还有的只回一行纯文本。**捞不到就不啰嗦**，别把整段 JSON 塞进日志。
 */
async function readError(res: Response): Promise<string> {
  let text = '';
  try {
    text = (await res.text()).slice(0, 800);
  } catch {
    return '';
  }
  try {
    const o = JSON.parse(text) as { error?: { message?: unknown } | string; message?: unknown };
    const msg = typeof o.error === 'object' && o.error ? o.error.message : o.message ?? o.error;
    if (typeof msg === 'string' && msg.trim()) return msg.trim().slice(0, 200);
  } catch { /* 不是 JSON，按纯文本处理 */ }
  return text.replace(/\s+/g, ' ').trim().slice(0, 200);
}
