/**
 * 把事实拼成一句给模型的话。
 *
 * **不用「一只鱼站在……」这种句式。** 空镜的关键是：说清在哪、什么光、什么天气、
 * 什么质感，然后明确要求「没有人物、没有文字」。不写「没有人物」的话，
 * 模型很爱往画面里塞一个人 —— 那不是她，是一个陌生人站在她的照片里。
 *
 * 这一段是纯函数，测试直接喂数字验，不用起网络。
 */
/**
 * 四条通用尾巴。
 *
 * 不管拍什么都要有的：**没有人物、没有可读文字**。这两条是硬约束 ——
 * 不写「没有人物」，模型很爱往画面里塞一个陌生人；不写「没有文字」，
 * 中文招牌生成出来必然是乱码。
 */
/**
 * 剪掉句子里的某几个分句（2026-11-10 全量体检）。
 *
 * 季节句和回避句是按「城市 + 月份」写的长句，里面混着好几件事：
 * 植被、地面、天空、日照。但它们被追加到**任何题材、任何时刻**的照片上 ——
 * 于是半夜的街景会带着「天空是一整片灰白低云」，白天的晴天会带着
 * 「没有太阳也没有影子」。
 *
 * 判据：**一句话里只要有一部分此刻不成立，就把那部分剪掉，别整句照搬。**
 */
function slimClause(text: string, drop: RegExp): string {
  if (!text) return '';
  return text
    .split(/[；;]/)
    .map((x) => x.trim())
    .filter((x) => x && !drop.test(x))
    .join('；')
    .replace(/^[，、；]+|[，、；]+$/g, '');
}

/*
 * **硬约束压短（2026-11-11 真机实测之后）。**
 *
 * 原来这句 30 字，`NO_TEXT` 又是 33 字，两条加起来 63 字 —— 占了整个提示词的四分之一，
 * 而它们只是「别画错」的兜底，不是画面内容。
 *
 * 压短不等于削弱：「画面里没有人」这六个字是模型最认的形态，
 * 后面那串「（或者只有远处的背影…）」是给人看的解释，对模型只是噪音。
 */
const NO_PEOPLE = '画面里没有人物';
/*
 * ## 景区要有人气（2026-11-12 晚，Mr.Q：「得有人，景区有人气最好，就是别太突出了」）
 *
 * 上一版把「顶多远处的背影」删成了硬邦邦的「画面里没有人物」，
 * 结果整条街、整座古城、整片海滩一个活人都没有 —— 那是**布景**，不是有人住的地方。
 *
 * 但「有人」不能交给模型自己拿主意：它会给你一个正对镜头的大活人，或者一排摆拍的路人。
 * 所以量词、距离、清晰度三样都写死：**远处、零星、虚化、看不清脸**。
 *
 * 特写（食物、小物）不在此列 —— 一碗饺子边上站着人，那是另一张照片。
 */
const SOME_PEOPLE = '近处空着，远处几个虚化的人影，看不清脸';
/*
 * **开阔风景（海滩、湖岸、广场）要另一句（2026-11-12 晚实图）。**
 *
 * 「远处几个虚化的人影」在街景那条里正好：有纵深引导线，人自然落在远处。
 * 换到海滩就不行 —— 沙滩没有收束，模型把「人影」理解成一个走在画面中间的大背影，
 * 加一句「近处空着」也压不住。
 *
 * 换成给它**尺寸**：「散着几个很小的行人」。「很小」是模型真认的词，
 * 「远处」它只当形容词。
 */
const FAR_PEOPLE = '远处散着几个很小的行人，看不清脸';
const NO_TEXT = '不要出现可读的文字和水印';
/** 硬约束那一句在哪儿 —— 季节句、体感句都往它前面插。两种措辞都要认。 */
const hardAnchorAt = (base: string): number =>
  Math.max(base.lastIndexOf(NO_PEOPLE), base.lastIndexOf(SOME_PEOPLE));

/**
 * 一道菜该用哪套器物。
 *
 * ## 为什么要把「碗里是什么」和「碗是什么」分开
 *
 * 2026-11-07 用户发来一张图：拍的是**担担面**，出来的是一碗清汤面，浮着几片白萝卜、
 * 一撮香菜、一层红油。那是兰州牛肉面 —— 而它当时是**所有中国面食的共用模板**：
 *
 *   `WARE_CN.noodle = '白瓷大碗，汤色清亮能看见碗底，表面一层红油泼辣子没搅开，
 *                      浮着几片白萝卜、一撮翠绿香菜…'`
 *
 * 于是一碗清汤面被安到了 81 道「命中 /面|粉/」的菜上。担担面是**干拌、没有汤**
 * （四川省政府词条原话：「面细无汤，臊子酥香」），套上去就必然是错的。
 *
 * ## 所以分两层
 *
 * - `dishKind()` 只管**容器**（碗 / 盘 / 杯 / 笼 / 锅 / 砧板），决定焦在哪、冒不冒热气；
 * - `DISH_LOOK` 管**碗里到底是什么**，按菜名逐一写，先命中先用；
 * - 都没命中，才退回 `wareCn()` 的通用器物 —— 而通用器物里**不许写任何一地的地方特征**。
 *
 * 「写死一地」正是这个 bug 的根：模板不认菜，也不认地方。
 */
type DishKind =
  | 'noodle' | 'bowl' | 'pot' | 'hotpot' | 'grill' | 'tea' | 'cake'
  | 'bread' | 'jelly' | 'drink' | 'plate';

/**
 * 按菜名判容器。
 *
 * **先排除，再认定。** 原来一条 `/面|粉/` 打天下，于是「粉红果仁糖塔」因为有「粉」
 * 字被画成一碗面，「Choripán 烤肠面包」「苏打面包」也全成了汤面 —— 实测 81 道
 * 命中 noodle 的菜里，33 道根本不是面条。
 *
 * 顺序也是逻辑：面包碗先于面包，蒸锅先于汤，肠粉先于「粉」。
 */
export function dishKind(dish: string): DishKind {
  const d = dish;
  /* 挖空面包当碗 —— 必须先于「面包」，否则会被当成一块面包。 */
  if (/面包碗|浓汤面包/.test(d)) return 'bowl';
  /* 面团制品：烤的、蒸的、夹的，全都没有汤，也不在碗里。 */
  if (/面包|面团|面球|面饼|面疙瘩|通心粉|意面|馕坑|贝果|三明治|汉堡|披萨|哈恰普里|炸面包/.test(d)) return 'bread';
  /* 凝冻类：凉粉/凉皮/酿皮切条凉拌，是「块」不是「条」。 */
  if (/凉粉|凉皮|酿皮|碗托|碗坨|土笋冻|薯粉饺/.test(d)) return 'jelly';
  /* 酒与饮料：一杯啤酒不该装盘。 */
  /*
   * **「啤酒鱼」「啤酒炖牛肉」是菜，不是酒。** 按 `/啤酒/` 一刀切，
   * 阳朔的啤酒鱼会变成一只玻璃杯。
   */
  if (/啤酒鱼|啤酒炖|啤酒鸭/.test(d)) return 'pot';
  if (/啤酒|葡萄酒|红酒|白酒|格瓦斯|蜂蜜酒|金水酒|Kölsch|Goldwasser|riesling|Bikavér|威士忌|伏特加|清酒|咖啡/.test(d)) return 'drink';
  /* 凝冻类的另一种写法：葛根粉冲成胶糊，不是一碗粉。 */
  if (/葛根粉/.test(d)) return 'jelly';
  /* 炖菜端的是锅 —— 「小鸡炖蘑菇」原来是一盘菜。 */
  if (/炖|焖|煨/.test(d) && !/酸奶油|酸奶/.test(d)) return 'pot';
  /* 一盆红油里的菜，容器是深盆，不是盘。 */
  if (/毛血旺|水煮鱼|水煮牛肉|佛跳墙|卤煮/.test(d)) return 'bowl';
  if (/火锅|锅底|串串|麻辣烫/.test(d)) return 'hotpot';
  /*
   * 铁锅、砂锅、汽锅、煲 —— 这几道的辨识点就是容器本身。
   * 「三亚的椰子鸡」丢掉锅就成了一盘鸡块。
   */
  /*
   * 「青口锅」是连锅端上来的。判据是**有没有「锅」这个字**，但三个例外要先剔：
   * 锅包肉（一盘）、锅贴（一盘）、锅巴菜（一碗）。名字以「锅」结尾不是必要条件 ——
   * 「青口锅配薯条」「青口锅 moules」尾巴上都不是锅字。
   */
  if (/锅/.test(d) && !/锅包肉|锅贴|锅巴菜|二锅头/.test(d)) return 'pot';
  if (/铁锅|石锅|汽锅|砂锅|干锅|煲$|鸭脚煲|焖锅|地锅|浑锅|一品锅|下锅|沾沾|辣糊糊|汤锅|椰子鸡|姜母鸭|酸汤鱼|红焖羊肉/.test(d)) return 'pot';
  /* 汤、粥、羹、糊：必须有一个有深度的容器，摊在盘子上物理上不成立。 */
  if (/汤|粥|羹|糊|泡馍|汤圆|鱼丸|肉燕|清补凉|双皮奶|酸奶|糖水|狮子头|凉虾|锅巴菜/.test(d)) return 'bowl';
  /* 米皮/河粉类：薄透、干捞、上盘。 */
  if (/肠粉|陈村粉|卷筒粉|冷粉/.test(d)) return 'plate';
  /* 早茶点心才进蒸笼。酥油茶、甜茶、蒙古锅茶、汕尾菜茶都不是。 */
  if (/早茶|茶点|虾饺|烧卖|凤爪|点心|小笼|灌汤包|三丁包|包子|蒸饺/.test(d)) return 'tea';
  if (/菜茶/.test(d)) return 'bowl';
  /*
   * 茶是液体 —— 一碗酥油茶不该配一笼虾饺。
   * 但「沙茶面」「下午茶的司康」「茶干」里有「茶」字却是面、是点心、是豆干。
   */
  if (/茶/.test(d) && !/茶面|茶干|茶油|茶饼/.test(d)) {
    /* 下午茶那半截说的是点心，茶是配角。 */
    if (/司康|松饼|三明治|蛋糕/.test(d)) return 'cake';
    return 'drink';
  }
  if (/蛋糕|蛋挞|羊角|可颂|甜甜圈|泡芙|布丁|冰淇淋|果仁糖|tarte|strudel|酥$|糖塔|炸糕|油糕|粑|糕$|诺克/.test(d) && !/约克郡|烤肉|薄饼/.test(d)) return 'cake';
  /* 真的面条/粉：要求「面/粉」在词尾或紧跟限定词，别再让地名和形容词参与。 */
  /*
   * `饺子$` 不算面条：一盘饺子在盘子里，不管中国的还是波兰的。
   * 归进 `noodle` 会让「华沙的波兰饺子」变成一碗汤，还会冒热气。
   */
  if (/面$|面线|拉面|炒面|拌面|冷面|凉面|面片|揪面|刀削|河漏|栲栳栳|米线|粉丝|粉$|河粉|粿条|馄饨|抄手|云吞|饸饹|拨鱼|片儿川/.test(d)) return 'noodle';
  /*
   * 「烧」不能单独算 —— 中文里它一半是烤（烧鹅、烧腊），一半是炖（红烧肉、烧茄子）。
   * 原来 `/烤|烧/` 让红烧肉变成了一盘炭火上的肉串。先剔掉「红烧」，再认烤。
   */
  if (/红烧|烧茄子|烧豆腐/.test(d)) return 'plate';
  /* 烤饺子、烤馅饼是炉子里出来的，不是架子上串着的。 */
  if (/empanada|馅饼|饺子|肉饼/i.test(d)) return 'plate';
  if (/烤|炙|串|烧腊|烧鹅|烧鸭|叉烧|烧肉/.test(d)) return 'grill';
  return 'plate';
}

