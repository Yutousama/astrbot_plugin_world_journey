/**
 * 欧洲的「节」。
 *
 * ## 为什么不能共用中国那套
 *
 * 上面那套写的是春节灯笼、清明青团、端午粽子、中秋月饼 —— 全是中国的节。
 * 欧洲城市拍「节」会出一整条挂满红灯笼的巷子，而那在柏林不存在。
 *
 * 这里只按**月份**给，不认具体节日：欧洲的节太多，逐个列会错；
 * 但「十二月是圣诞集市、夏天是露天座位、秋天是南瓜和栗子」
 * 这三件事在几乎每座城里都成立，画出来也对得上。
 */
/**
 * 剥掉任何句子（季节句、节日文案、城市锚点）里「天是什么样」的那些分句。
 *
 * 判据只有一条：**天的颜色只有一个来源**（`skyLine` / `skyOf`），
 * 别的句子一律不许说天。见到了就剥，不看情况 ——
 * 2026-11-12 之前是「按情况剥」（只在夜里和晴天剥），
 * 于是傍晚那张里既有「暖光」又有「灰白低云、没有太阳」。
 */
function stripSkyClauses(text: string): string {
  if (!text) return '';
  return slimClause(
    text,
    /天空|天光|天色|日照|阳光|太阳|蓝天|低云|云是|云很|云压|少云|积云|铅灰|天还亮|天黑得早/,
  );
}

/**
 * 夜里还剩什么季节信息：**只留「存在物」，砍掉「颜色」。**
 *
 * ## 为什么不能整段砍掉（2026-11-12 实图之后）
 *
 * 上一条规则是「没有日光就不写季节」—— 那是为了解决「黑着的照片里说银杏金黄」。
 * 但一刀切下去，把**不依赖光线的事实**也砍了：
 *
 * 柏林十二月十七点（天已黑透、地上有雪），提示词里一个「雪」字都没有，
 * 出来是一条**干净的湿街**。而那天柏林零下、屋顶和窗台都压着雪。
 * 一张没雪的柏林冬夜，比一张过曝的黄昏更容易被一眼认出是假的。
 *
 * 所以按**能不能在黑暗里知道**来分：
 * - 砍：叶、花、颜色、光斑 —— 「银杏金黄」「三角梅在开」夜里看不见；
 * - 留：雪、冰、湿、积水、石板、水面 —— 踩上去知道，灯下也认得出。
 */
function nightSeason(text: string): string {
  if (!text) return '';
  return text
    .split(/[；;]/)
    .map((x) => x.trim())
    .filter((x) => x && /地面|雪|冰|霜|湿|积水|石板|水面|河|湖|土|沙|泥|雾/.test(x))
    .join('；');
}

/**
 * 季节句进城（2026-11-15）。
 *
 * 季节模板是按**地区**写的，不是按城写的：西北十一月那条
 * 「地面是干土，尘土浮在鞋面上」在敦煌城外成立，在兰州市区的滨河路上不成立 ——
 * 那儿铺的是沥青，鞋上不该有土。
 *
 * 只换这一处，不建全量对照表：**替换一条能说清来由的，比编一张映射表可靠。**
 * 白天和夜里分两句，因为夜里的规范是「灯下认得出」，不是「看得见尘土」。
 */
function citySeason(text: string, daylit: boolean): string {
  if (!text) return '';
  const city = daylit ? '路面干，道牙和墙根积着一层灰' : '路面干，灯下是一层薄灰';
  return text.replace('地面是干土，尘土浮在鞋面上', city);
}

/**
 * 展厅里的光（2026-11-15）。
 *
 * 判成室内（`spotIndoor`）的点不能走户外灯句 —— 站在展厅里看不见「路灯和楼窗」。
 * 也不能走 `lightLine({ indoor: true })`：那一支是食物特写用的
 * 「一盏暖黄的灯从上方罩下来，桌面反光」，套在展柜上会变成一张餐桌。
 */
function hallLight(sun: SceneSun): string {
  if (sun.whiteNight) return '顶灯和射灯照着展柜，外面那层光还没退干净';
  if (sun.daylit) return '光从高窗落下来，展柜玻璃上有一块反光';
  return '顶灯和射灯照着展柜，展柜以外的地方暗下去';
}

/**
 * 节日那张的光。
 *
 * 这一类画面是**一堆东西挤在一起**，要的是「颜色浓、层次少」，不是精确的影子长度。
 * 但「自然光」那句仍然不能用 —— 夜里它会把整条街提亮，
 * 这个坑在 `ground` 那条踩过两次，别在这里再犯一遍。
 */
function festivalLight(scene: PhotoScene): string {
  const s = sceneSun(scene);
  if (s.whiteNight) return '天没有黑透，光偏白，颜色仍然浓';
  if (!s.daylit) return '光只有灯和窗，暗部重，颜色反而更浓';
  if (s.overcast) return '光被云压平，没有影子，颜色很饱和';
  return '光偏低或偏斜，颜色比平时饱和';
}

