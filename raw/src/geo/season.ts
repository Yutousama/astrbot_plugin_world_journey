/**
 * 一座城属于哪个气候区。
 *
 * 三层：**单城表 → 国家兜底 → null**。
 *
 * 2026-11-07 之前是两层（单城 → 国家），国家表里只有俄波，
 * 于是巴黎、伦敦、东京、悉尼这些城市全都返回 null，一句季节都不生成。
 * 现在加了国家兜底，漏写单城表也不会一句话都不说。
 *
 * 中国走另一条路：省份表（91 座城，按省份分比按城市分省事）。
 */
export function regionOf(
  city: { id: string; region: string; country: string },
): SeasonRegion | null {
  if (city.country === 'CN') {
    return BY_CITY[city.id] ?? BY_PROVINCE[city.region] ?? null;
  }
  return CLIMATE[city.id] ?? BY_COUNTRY[city.country] ?? null;
}

/** 月份 → 五档。冬天跨年，12/1/2 合成一档。 */
type Slot = 'spring' | 'summer' | 'autumn' | 'lateAutumn' | 'winter';

/**
 * 月份 → 季节档。**南半球要倒过来。**
 *
 * ## 为什么这件事非做不可
 *
 * 2026-11-07 之前这个函数只吃月份。那时候还没关系 —— 南半球城市
 * （布宜诺斯艾利斯、里约、悉尼、奥克兰、伊瓜苏、乌斯怀亚）全都没配气候区，
 * 一句季节都不生成，错得「安静」。
 *
 * 一旦给它们配上气候区，一月的布宜诺斯艾利斯就会拿到「冬天」那一条：
 * 光秃的树、铅灰的天。而那里一月是盛夏，梧桐正浓绿、气温三十度。
 *
 * ## 怎么倒
 *
 * 直接把月份往后推六个月再套同一套规则。`LOOK` 里的文案是按季节写的，
 * 不认月份，所以**同一套文案南北半球都能用** —— 前提是文案里不出现
 * 「四五月」「正月」这种具体月份的锚点（中国的几条有，但那些只给中国城市用）。
 */
function slotOf(month: number, lat = 45): Slot {
  const m = lat < 0 ? ((month + 5) % 12) + 1 : month;
  if (m >= 3 && m <= 5) return 'spring';
  if (m >= 6 && m <= 8) return 'summer';
  if (m === 9 || m === 10) return 'autumn';
  if (m === 11) return 'lateAutumn';
  return 'winter';
}

