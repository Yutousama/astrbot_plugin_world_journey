/**
 * 「这个时节，这里长什么样」—— 2026-11-07
 *
 * ## 为什么要有这个文件
 *
 * Mr.Q 发来一张图：她在承德（避暑山庄），气温零下二度，生出来的画面是
 * **红灯笼 + 绿柳 + 湿石板路 + 白墙黑瓦** —— 那是江南水乡的意象。
 *
 * 查下来不是没有视觉锚点（128 座城全有），锚点也写了「园林湖面开阔、古松成片、
 * 丹霞石柱、金顶黄琉璃」。问题是**提示词里没有任何一句说「现在是冬天」**：
 *
 *   `九月承德的避暑山庄，园林湖面开阔，岸边古松成片…，天气晴。`
 *
 * 模型只能拿「承德 + 湖 + 园林」去联想，一联想就到江南去了。
 *
 * 所以这个文件只干一件事：**把月份和地域翻译成画面**。树木什么状态、地面什么质感、
 * 水结不结冰、天什么颜色 —— 全是可以画出来的东西，不是形容词。
 *
 * ## 数据来源
 *
 * 2026-11-07 让子 agent 按气候区查证过一轮（气候资料、实景记录、旅游攻略、官方景区说明）。
 * 承德那一段单独立了 `CHENGDE_WINTER`：它虽然是仿江南造的皇家园林，但和江南民居水巷
 * 完全不是一回事 —— 青砖灰瓦 vs 白墙黑瓦、大冰面 vs 活水窄巷。这层区别不写清，
 * 模型永远会往江南跑。
 *
 * ## 只给中国城市
 *
 * 国外城市的季节特征没查过，硬套就是编。`regionOf()` 对国外返回 null，
 * 调用方按「没有季节修正」处理 —— 保持现状，不比现在更糟。
 */

