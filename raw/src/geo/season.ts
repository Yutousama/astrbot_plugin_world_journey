/**
 * 承德避暑山庄：仿江南造的皇家园林，但不是江南。
 *
 * 模型最容易在这儿串味 —— 「湖 + 园林 + 古建」一出现就往江南民居水巷跑。
 * 所以这一条把**区别**直接写出来，而不只是描述它长什么样。
 */
const CHENGDE_WINTER =
  '这里是北方的皇家园林，不是江南水乡：墙是青砖灰调、屋顶是灰色筒瓦，'
  + '不是白墙黑瓦；水是一整片开阔湖面、中间有洲岛和长堤，不是贴着民居的窄河道；'
  + '房子是宫殿式大殿和二层楼阁，间距大，没有商铺和幌子；背景是占了大半园子的山峦和成片古松。'
  + '十一月末湖面已经冻成灰白冰板，冰上立着成片折断的褐色枯荷梗；'
  + '岸边的垂柳只剩细枝，油松是画面里唯一的深绿；朱红门窗和深棕原木柱，没有彩画。';

/**
 * 一句话：这个月在这座城，画面应该是什么样。没有就返回空串。
 *
 * `city` 允许只传关键字段，测试里不必造完整对象。
 *
 * **`lat` 可选但很重要**：南半球的季节是反的。不传按北纬 45° 处理
 * （等于「当北半球」），所以传了完整 `City` 的调用方一定要带上它 ——
 * 布宜诺斯艾利斯一月是盛夏，不是冬天。
 */
export function seasonLine(
  city: { id: string; region: string; country: string; lat?: number } | null | undefined,
  month: number,
): string {
  if (!city) return '';
  const r = regionOf(city);
  if (!r) return '';
  const m = ((Math.trunc(month) - 1) % 12 + 12) % 12 + 1;
  /* 承德 + 冬半年才用特例：夏天的避暑山庄确实该是浓绿湖区，那是对的。 */
  if (city.id === 'chengde' && (m === 11 || m === 12 || m === 1 || m === 2 || m === 3)) {
    return CHENGDE_WINTER.replace(/。+$/, '');
  }
  return LOOK[r][slotOf(m, city.lat)].replace(/。+$/, '');
}

/**
 * 这一张**不该**出现的意象。只在提示词末尾追加，且只给会串味的地方。
 *
 * 云端接口没有负向提示词这个参数（只有 ComfyUI 有），所以只能写成
 * 「这里不是…」这种正面否认句 —— 比不写强，但不如 ComfyUI 的 negative 干净。
 *
 * ## 为什么只给中国城市
 *
 * 不是因为国外不会串味，是因为**这一句本身有副作用**：否定句在生图模型上
 * 经常被读成强调，「没有雪」反而把「雪」塞了进去。
 *
 * 所以只有一种情况值得冒这个险：**同一个国家内部、同纬度的两块地方
 * 长得完全不一样**（北方的冬天 vs 江南的冬天）。欧洲那五个区之间没这么用 ——
 * 西欧「草地常绿、几乎不积雪」和中欧「屋顶积雪留几天」是靠**正面描述**
 * 分开的，加一句「不是北欧的雪」只会往画面里塞雪。
 */
export function avoidLine(
  city: { id: string; region: string; country: string; lat?: number } | null | undefined,
  month: number,
): string {
  if (!city || city.country !== 'CN') return '';
  const r = regionOf(city);
  if (!r) return '';
  const slot = slotOf(((Math.trunc(month) - 1) % 12 + 12) % 12 + 1, city.lat);
  const winter = slot === 'winter' || slot === 'lateAutumn';
  if (!winter) return '';
  /* 承德的冬半年有自己那段 `CHENGDE_WINTER`，已经把「不是江南」说透了，不再叠一遍。 */
  if (city.id === 'chengde') return '';
  switch (r) {
    /*
     * **北方的否定句也去掉了（2026-11-11 真机实测 + 本文件下面那段注释）。**
     *
     * 原来写着「不是江南水乡：没有白墙黑瓦、没有绿柳和荷叶、没有湿石板反光、没有小桥流水」——
     * 这一整句 36 字，把「白墙黑瓦」「乌篷船」「小桥流水」这些词**塞进了模型脑子里**。
     *
     * 下面 jiangnan 那条分支的注释早就写着：「否定句在生图模型上经常被读成强调」。
     * 知道归知道，这两条一直没改。
     *
     * 真机验过：60 字的那条提示词**没有任何否定句**，画出来照样是川西木构街 ——
     * 因为锚点里正面写了「穿斗木构、青瓦坡顶、白灰墙夹木壁板」。
     * **正面写清楚，比反面拦一百遍管用。**
     */
    case 'north':
    case 'northwest':
      return '';
    /*
     * **川渝留天气、不留形制（2026-11-11）。**
     *
     * 原来那句「不是江南水乡：没有白墙黑瓦和石桥，也没有蓝天和阳光，画面是灰白的」
     * 把「白墙黑瓦」「石桥」这两个词直接塞给模型 —— 越是说"没有"，越容易画出来。
     * 但「灰白」「没有太阳」是**真实的天气基调**，川渝冬天确实日照极少，这句要留。
     *
     * 所以只留后半段，改成正面陈述，不提任何形制。
     */
    case 'sichuan':
      return '天色常是灰白的，看不见蓝天，也没有太阳';
    /*
     * 江南不需要这一句。
     *
     * 北方的冬天（秃树 + 雪泥 + 冰板）串到江南来，靠的是江南那一大段**正面描述**挡住的：
     * 香樟常绿、蜡梅开黄花、石板潮、池水不冻、枯荷梗立着。这些写清楚了，模型自然画不出大雪。
     * 反过来写「没有齐膝积雪」，等于把「雪」这个词塞进它脑子里 —— 否定句在生图模型上
     * 经常被读成强调。
     */
    case 'jiangnan':
      return '';
    default:
      return '';
  }
}
