/**
 * 这个地点到底是什么类型的地方。
 *
 * ## 为什么要有这一层（2026-11-14，Mr.Q 报的「敦煌博物馆建在沙漠里」）
 *
 * 生图提示词原来是这么拼的：
 *
 *   有景点专属锚点 → 用锚点（准）
 *   没有          → `敦煌博物馆。周边一带是<敦煌城市锚点>`（错）
 *
 * 而敦煌的城市锚点是「党河两岸窄绿洲…**出城就是连片沙丘**，沙脊锋利」——
 * 那是**整座敦煌的平均长相**，套在市区里的一个博物馆上，博物馆就搬进了沙丘。
 *
 * 代码里早写着这条的死结：
 *
 *   > 真正的解法是景点级锚点（一个景点一条），但 185 城 × 7 个景点 = 1300 条
 *
 * 查了一下实际数据：`SPOT_LOOK` 只有 **60 城 136 条**，覆盖率约 15%。
 * 也就是说剩下 85% 的点全在走城市锚点 —— 这不是个例，是默认行为。
 *
 * 所以不再往「一个点一条」的方向补。改成先判两件事：
 *
 *   ① **类型** —— 博物馆 / 石窟 / 关隘 / 夜市……
 *   ② **在哪** —— 城里的街区 / 城外的野地
 *
 * 这两条是**地点自身的事实**，不依赖谁去写描述；有了它们，
 * 「博物馆不该在沙丘边上」就不再靠人记得，而是结构上不发生。
 *
 * ## 这一层**不写**什么
 *
 * 不写「这栋楼是什么样」。那是她的活（`PhotoScene.describe`）。
 * 这里只给一句话的**形制**（室内 / 崖面 / 土筑），因为它决定画面里
 * 出现的是墙还是沙子，而且模型光看地名判不出来。
 *
 * 判据界线：**去掉这句，画面会跑到另一个物种上去** → 留；
 * **去掉这句，只是少了个形容词** → 不留。
 */

/**
 * 地点类型。刻意不做细 —— 分得越细，「判错」的面积越大，而每一类都要配一句话。
 * 这里每一类都对应一个**画面里必须成立的东西**（室内 / 有屋顶 / 在崖上 / 在野外）。
 */
export type SpotKind =
  | 'museum'   // 室内展馆
  | 'cave'     // 崖壁石窟
  | 'temple'   // 宗教建筑，有院墙屋顶
  | 'fort'     // 关城、城墙、土堡
  | 'palace'   // 宫堡式建筑群
  | 'mountain' // 山体
  | 'water'    // 水面
  | 'street'   // 城内街巷
  | 'bridge'   // 桥
  | 'market'   // 市集夜市
  | 'geology'  // 雅丹、丹霞、石林这类地貌
  | 'ruins'    // 遗址、故城、陵墓
  | 'park'     // 园林、公园
  | 'tower'    // 塔、楼、碑这类单体的标志物
  | '';

/** 在城里还是在野地。二分就够 —— 判细了没有数据支撑。 */
export type SpotSetting = 'urban' | 'wild' | '';

export interface SpotProfile {
  readonly kind: SpotKind;
  /** 画面里有屋顶、有墙、有室内。这一条决定它不可能出现在荒漠里。 */
  readonly indoor: boolean;
  readonly setting: SpotSetting;
  /**
   * 一句话形制。**不写地方特征，不写风格。**
   * 只在没有专属锚点时拼进提示词，长度压到 6–14 字。
   */
  readonly form: string;
}

const NONE: SpotProfile = { kind: '', indoor: false, setting: '', form: '' };

/**
 * 判定顺序即优先级，**先排除再认定**。
 *
 * 这是被同一类错误教出来的：`/面|粉/` 一条正则把「粉红果仁糖塔」判成了面条，
 * 把「鸡豆凉粉」判成了面（见卷二 §1）。凡是「只要含某个字就算」的规则，
 * 一定要先在它前面挡掉那些**含这个字但根本不是这个东西**的名字。
 *
 * 下面每条 `[正则, 类型]` 从上往下第一个命中即用，所以排除项写在前。
 */
