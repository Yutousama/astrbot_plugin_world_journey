  cave: '崖壁上开凿的窟龛',
  temple: '院墙围着的殿宇',
  fort: '土筑或砖包的城墙，垛口连续',
  palace: '依地势叠起的建筑群',
  /*
   * **自然类（山 / 水面 / 地貌）刻意留空。**
   * 「西湖」这个名字已经说清它是水，再补一句「水面占住画面大半」只是占字数 ——
   * 判据是「去掉这句，画面会不会跑到另一个物种上去」：不会。
   * 而「敦煌博物馆」去掉「室内，展柜和展墙」就可能画成一栋楼的外立面，所以要留。
   */
  mountain: '',
  water: '',
  street: '两侧立面夹着街面',
  bridge: '桥面往前铺开，两侧是栏杆',
  market: '成排的摊位和棚子',
  geology: '',
  ruins: '残存的墙基和台地',
  park: '园里的水面和树',
