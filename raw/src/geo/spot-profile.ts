/**
 * 判一个地点。
 * 判不出来就返回空档 —— **不猜**。
 * 空档的后果只是「照旧走城市锚点」，而猜错的后果是一张内容不对的照片。
 */
export function spotProfile(spot: string | undefined): SpotProfile {
  if (!spot) return NONE;
  /*
   * 括号里的补充说明不参与判定。
   * 「沙湖（石嘴山平罗县，单算半天）」里的「石嘴山」差点让沙湖被判成山 ——
   * 那是备注，不是地名。
   */
  const name = spot.replace(/[（(][^）)]*[）)]/g, '').trim();
  if (!name) return NONE;
  /* 后缀优先，判不出才退回包含规则。 */
  const hit = SUFFIX.find(([re]) => re.test(name)) ?? RULES.find(([re]) => re.test(name));
  if (!hit) return NONE;
  const kind = hit[1];
  /* 表里不会出现空类型，这一行是为了把 `''` 从类型里收掉，让 `FORM[kind]` 站得住。 */
  if (!kind) return NONE;
  const setting: SpotSetting = URBAN_KINDS.has(kind) ? 'urban'
    : WILD_KINDS.has(kind) ? 'wild'
    : '';
  return { kind, indoor: INDOOR.has(kind), setting, form: FORM[kind] };
}

/**
 * 给她看的一句话：「（室内展馆，在市区）」。
 *
 * 挂在她每回合都读的 `{{journey.now}}` 里（`nowSummary` 的「此刻在X」那一行），
 * 以及 `journey_now` 的回执 —— 两处同一个来源，不会说出两种话。
 *
 * **只给事实，不给指令。** 不加「拍照时按这个写」这类话：
 * 那是 `journey_photo` 的工具描述和 ENV_PROMPT 该说的，混进事实里就成了命令。
 *
 * 称呼用「性质」而不是类型名：`敦煌博物馆（博物馆）` 是废话，
 * `敦煌博物馆（室内展馆，在市区）` 才多给了她一件不知道的事。
 */
const KIND_LABEL: Record<Exclude<SpotKind, ''>, string> = {
  museum: '室内展馆',
  cave: '崖壁石窟',
  temple: '寺庙院落',
  fort: '关城',
  palace: '宫堡建筑群',
  mountain: '山',
  water: '水面',
  street: '街区',
  bridge: '桥',
  market: '市集',
  /* 「地质景观」不带「野外」—— 位置那一半紧接着会说，重复一遍是废话。 */
  geology: '地质景观',
  ruins: '遗址',
  park: '园林',
  tower: '塔楼',
};

export function spotKindLine(spot: string | undefined): string {
  const p = spotProfile(spot);
  if (!p.kind) return '';
  const where = p.setting === 'urban' ? '，在市区' : p.setting === 'wild' ? '，在野外' : '';
  return `（${KIND_LABEL[p.kind]}${where}）`;
}

/**
 * 城市锚点里的分句，哪些**不该**出现在这个地点周围。
 *
 * 只做减法，不重写 —— 城市锚点的那几句话是有人看过真地方写的，别动它。
 * 剔的判据是「这句话描述的东西，在这个类型/位置的地点旁边存在吗」。
 *
 * 只有 **urban** 的地点才剔野外地貌。「敦煌博物馆」剔掉「出城就是连片沙丘」，
 * 但「鸣沙山」（wild）一个字都不动 —— 它本来就在沙丘里。
 */
const WILD_ONLY = /沙丘|沙漠|戈壁|荒原|雅丹|丹霞|石林|土林|雪山|冰川|峡谷|草原|盐湖|荒漠|戈壁滩|雪线|冰原/;

export function trimVistaFor(vista: string, profile: SpotProfile): string {
  if (!vista) return '';
  if (profile.setting !== 'urban') return vista;
  /*
   * **从第一个野外片段起，整段砍掉** —— 不是逐句剔。
   *
   * 第一版逐句剔，被这句话打回来了：
   *
   *   党河两岸是窄绿洲，…白杨葡萄架夹着巷子，出城就是连片沙丘，**沙脊锋利**。
   *
   * 「出城就是连片沙丘」被剔掉了，「沙脊锋利」不含任何地貌词，留下了 ——
   * 而它正是沙丘的下一句。分句切割把语义单元切断了，逐句判永远补不完。
   *
   * 换判据：锚点写野外时几乎都带转折（「出城就是」「城外」「远处是」），
   * 转折之后的部分整块都是野外的。所以找到第一个野外片段，砍到结尾。
   */
  const pieces = vista.split(/(?<=[，。；])/);
  const first = pieces.findIndex((p) => WILD_ONLY.test(p));
  if (first < 0) return vista;
  const out = pieces.slice(0, first).join('').trim();
  /*
   * **尾部标点去掉，由调用方补。** `photoPrompt` 拼的是 `${where}。` ——
   * 这里留一个句号就变成「…夹着巷子。。」。
   */
  const cleaned = out.replace(/[，；。]$/, '');
  /*
   * 砍完只剩零星几个字就不拼了 —— 「周边一带：党河」这种残句
   * 比不写更糟，模型会拿它当主体。
   */
  return cleaned.trim().length >= 8 ? cleaned : '';
}
