/**
 * 熟络度那一句（2026-11-08 Mr.Q：「对旅伴的好感系统可以完善一下」）。
 *
 * ## 为什么不能只报次数
 *
 * 「跟某某一起走过 3 次」是**账**，不是关系。第 3 次见面和一起待了 30 天，
 * 说出来的话一模一样 —— 时间在走，关系没走。
 *
 * ## 分档写，不按分数写
 *
 * 四档对应四件事：刚认识（客气）、熟了（开始不客气）、老朋友（会念叨）、
 * 老搭档（不用说话）。**同一档里按种子换句子**，同一天重算不变。
 *
 * 只写**动作**，不写「关系很好」这种结论 —— 结论由读的人自己得出。
 *
 * 这一档是唯一允许写「安静」的地方：最高档的意思就是「不用说话」，
 * 别处的安静是生分，这里的安静是默契。
 */
export function bondWith(who: string, warmth: number, seed: number): string {
  const w = warmthStep(warmth);
  if (w < 12) {
    return pick([
      `${who}还客气着，说话带「您」，你让别这样，笑了一下没接。`,
      `跟${who}认识没多久，走在一起中间总隔着半步。`,
      `${who}问你接下来打算去哪，你说没定，回一句「那正好」。`,
    ], seed);
  }
  if (w < 24) {
    return pick([
      `${who}已经不问「能不能」了，直接说「明天我想去那边」，说完就看着你。`,
      `跟${who}吃饭不用再让来让去，点各自想吃的，中间那盘一起动筷。`,
      `${who}记得你不吃香菜，点单的时候替你说了那句。`,
    ], seed);
  }
  if (w < 60) {
    return pick([
      `${who}走累了就把包递给你，一句解释都没有。`,
      `${who}说起以前一个人走的那几趟，说到一半停了，说「还是现在这样好」。`,
      `跟${who}不用安排，早上谁先醒谁去买早饭，回来另一个刚好洗漱完。`,
    ], seed);
  }
  return pick([
    `${who}已经能看出你什么时候不想说话，那种时候也跟着不说话。`,
    `${who}把行程本子推过来让你写，说「你比我记得清」。`,
    `跟${who}走路不用对表，谁走快了会自己慢下来。`,
  ], seed);
}

/**
 * 一起吃饭。
 *
 * ## 为什么单独写一个（2026-11-08）
 *
 * Mr.Q 看了一眼日程面板：「现在互动事件只有吃饭嘛」。
 *
 * 那时候确实只有晚饭那一格带着人：「晚饭，和慕容悠、玄月的大肥鱼、风子家的鱼宝宝一起，担担面」。
 * 白天的景点、傍晚的江边、夜里回住处 —— 全是她一个人。
 * 于是「一起旅行」只体现在一句固定的前缀里，读起来像个标签，不像有人在场。
 *
 * ## 为什么不写「和某某一起，菜名」
 *
 * 「和 A、B、C 一起，担担面」这句话里，人只是**状语**，把名字抠掉句子照样成立 ——
 * 那正是「标签感」的来源。所以这里让这个人**做一件事**：
 * 她点菜、她分你一半、她说想吃这个走了两站路。
 *
 * 菜名必须落在句子里（不是句尾硬接），三种餐次句式不同。
 *
 * ## 第三轮（1.0.5）：每句都要有一个「所以」
 *
 * 光是「她点了这个」还是一个人在吃饭。这一版每条都带着**后果**：
 * 抢了、剩了、换过来半碗、盘子往那边偏了 ——
 * 有后果的动作才占据两个人中间的那块桌子。
 *
 * ## 门槛：**从别人碗里夹东西，要有点交情**
 *
 * 「端上来先往你碗里夹一筷」「自己不动筷说怕烫」「你的被分了小半」——
 * 这是 24 分才有的动作。刚认识那天两个人各吃各的，最多「点了同一道」。
 */
export function dineWith(
  who: string, dish: string, meal: 0 | 1 | 2, seed: number, warmth = 0,
): string {
  /*
   * **主谓一律用 `who`，不写「她」。**
   *
   * 因为 `who` 可能是「小满」，也可能是**一群人**（`planDay` 传「小伙伴们」）。
   * 第一版写了「跟某某分了一份，她吃了大半」—— 三个人一起时出来是
   * 「跟小伙伴们分了一份，她吃了大半」，**主语换了，指代是断的**。
   * 动作也要容得下一群人：「把鞋脱了一只」这种只对一个人成立，换成「走得慢」。
   */
  if (meal === 0) {
    return pickBy([
      { t: `${who}起得比你早，带了一份${dish}回来，还是热的`, min: 12 },
      { t: `${who}出去买的，${dish}拎回来还烫手`, min: 12 },
      { t: `${who}说早上吃不下，最后你的${dish}被分了小半`, min: 24 },
      /* 刚认识那天早上不会有人替你带饭 —— 这一条就是给那天的。 */
      { t: `${who}先下楼了，说${dish}一会儿上去吃` },
    ], seed, warmth);
  }
  if (meal === 1) {
    return pickBy([
      { t: `跟${who}合点了一份${dish}，说好一人一半，最后谁也没算清谁吃多了`, min: 12 },
      { t: `${who}要的${dish}，你点了别的，吃到一半换过来半碗`, min: 24 },
      { t: `一人一份${dish}，${who}吃得比你快，吃完还看了你那份两眼`, min: 12 },
      { t: `${who}说这家${dish}查过点评，非要来，吃完说「你看我没说错吧」` },
      { t: `${who}点的${dish}，你点了别的，两盘放在中间谁也没先动` },
    ], seed, warmth);
  }
  return pickBy([
    { t: `${who}点了${dish}，你也来一份，端上来先往你碗里夹了一筷`, min: 24 },
    { t: `${who}把菜单推过来，说${dish}不点等于白来` },
    { t: `${who}说今天想吃${dish}，绕着走了两站路才找到` },
    { t: `${who}把${dish}推到你面前，自己不动筷，说怕烫`, min: 24 },
    { t: `${who}一边吃${dish}一边翻白天拍的照片，翻到一张糊的，先笑了`, min: 12 },
  ], seed, warmth);
}

/**
 * 在某个地方待着的那句中段。
 *
 * 原来只有 `MID_LINES`（「还在X，人比刚进来的时候多了」）—— 那是**一个人**的视角：
 * 她只会注意到人多不多。有人一起时，注意力会落到对方身上。
 *
 * 所以这一句不是给 `MID_LINES` 加个名字，是**换一个观察对象**。
 *
 * 这一组的共同形状是「她卡住了/她不想走了/她跟陌生人聊起来了」——
 * 都是**在同一个地方待着**才发生的事，正好跟夜里的「场景无关」互补。
 *
 * 「坐着不走，再待五分钟」是耍赖，「嫌你手抖」「说这里像小时候」是交底 ——
 * 都放在 12 / 24。看说明牌、蹲地上看、跟陌生人聊天，刚认识也成立。
 */
export function midWith(who: string, spot: string, seed: number, warmth = 0): string {
  return pickBy([
    { t: `还在${spot}，${who}蹲在说明牌前，看得比谁都慢` },
    { t: `还在${spot}，${who}坐在台阶上不走，说再待五分钟，五分钟过了还没动`, min: 12 },
    { t: `还在${spot}，${who}绕丢了一回，你在门口等了一会儿才见人出来`, min: 12 },
    { t: `还在${spot}，${who}把相机递过来让帮着拍一张，拍完看了三秒说重拍，手抖了`, min: 24 },
    { t: `还在${spot}，${who}蹲在地上看了很久，你问看什么呢，说不知道` },
    { t: `还在${spot}，${who}忽然说这里像小时候去过的某个地方，又说不清是哪`, min: 24 },
    { t: `还在${spot}，${who}跟门口那位老先生聊上了，你都没听清是怎么聊起来的` },
  ], seed, warmth);
}

/**
 * 夜里那一格。
 *
 * ## 三个坑（三轮踩出来的）
 *
 * **① `night` 不是短名词短语**，实际是 `nightOptionOf` 拼出来的**整句描述**：
 *
 * ```
 * 晚上，悦来茶园，成都市川剧院，折子戏常演，周末有整本
 * ```
 *
 * 所以第一版写成 `${night}，${who}说这条街跟她想的不一样` 出来是
 * 「…周末有整本，某某说这条街跟她想的不一样」—— **人在茶园里评价一条街**。
 *
 * **② 改成句号另起还是错**（1.0.4）：场景对上了，动作对不上 ——
 * 「半路停下来买水」「回去的路上」「走在你旁边」都**预设了「在路上」**，
 * 在剧场里、夜市摊前、酒店大堂全都不成立。
 *
 * **③ 所以这一版的池子只有一条硬规矩：场景无关。**
 * 说话、待着、算钱、不想回去 —— 这三种场合都说得通。
 * 句子也压到二十字上下：`night` 本身已经四五十字，后面再接长句这一格就爆炸了。
 *
 * ## 门槛：夜里最见关系
 *
 * 「一个人来大概就没意思了」「这趟出来值了」「下次还来」「看跟谁」——
 * 这几句一出口就定了关系的性质，**不是熟人不能说**。所以是这一组里门槛最高的
 * （36 / 60），而「算今天花了多少」「明天还去不去」谁都能说。
 *
 * 演出那一格由调用方跳过（《又见平遥》那种在台上演，没人说话）。
 */
export function nightWith(who: string, night: string, seed: number, warmth = 0): string {
  /*
   * **主语必须换手。**（1.0.5 第三轮）
   *
   * 上一版七条全以「某某说…」开头，连着看七天就是七句同一个开头 ——
   * 单句都合格，成组就腻。所以七条里让两条从「你」起句：
   * 一问一答比一个人一直说更像两个人在过日子。
   */
  const tail = pickBy([
    { t: `${who}说这地方一个人来大概就没意思了`, min: 36 },
    { t: `${who}说脚疼，说明天不走那么多了`, min: 12 },
    { t: `你问明天还去不去，${who}说去` },
    { t: `${who}把外套系在腰上，说不想那么早回去`, min: 24 },
    { t: `${who}说这趟出来值了，又补一句「下次还来」`, min: 36 },
    { t: `${who}在算今天花了多少，算到一半说不算了` },
    { t: `你问下次还来不来，${who}说看跟谁`, min: 60 },
  ], seed, warmth);
  return `${night.replace(/[。，,]\s*$/, '')}。${tail}。`;
}
